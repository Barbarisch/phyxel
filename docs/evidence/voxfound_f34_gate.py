"""F3.4 gate (VoxelFoundationPlan §9b): a SAVED world converted from PXB2 and drawn by the new store, next to today's
store drawing the same world. Project CityBench_C25 (a city generated by POST /api/settlement/build tier:city, saved
in its world.db: 64 chunks with 25 buildings). One engine session.
A = today's store (the streamed world, preview hidden); B = /api/debug/voxfound_preview {"source":"world_db"} over the
chunks -2..2 x 0..2 x -2..2 (the converter; today's world hidden). Debug tonemap curve 0, wind 0, GI off (§4.3), each
side captured twice (controls), 3D viewport only (CLEAN box), > 8/255. Diff maps saved.
usage: voxfound_f34_gate.py"""
import json, os, shutil, time, urllib.request

import numpy as np
from PIL import Image

API = "http://127.0.0.1:8120"
HERE = os.path.dirname(os.path.abspath(__file__))
P = "/api/debug/voxfound_preview"
CLEAN = (425, 105, 1195, 620)
POSES = {"city_high": [0, 110, 60, -90, -55], "city_oblique": [0, 85, 75, -90, -40], "city_close": [15, 70, 35, -110, -45]}
# (run 1, kept in f34_run1_badposes/: city_default sat in the grass, street_east looked into the void)


def call(m, p, b=None):
    r = urllib.request.Request(API + p, data=json.dumps(b).encode() if b is not None else None, method=m,
                               headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(r, timeout=900) as resp:
        return json.loads(resp.read().decode())


def shot(name, settle=4.0):
    time.sleep(settle)
    d = os.path.join(HERE, name)
    shutil.copy(call("GET", "/api/screenshot")["path"], d)
    return np.asarray(Image.open(d).convert("RGB")).astype(np.int16)


def diff(a, b):
    x0, y0, x1, y1 = CLEAN
    d = np.max(np.abs(a[y0:y1, x0:x1] - b[y0:y1, x0:x1]), axis=2) > 8
    return int(d.sum()), d


def pose(name):
    x, y, z, yaw, pitch = POSES[name]
    call("POST", "/api/camera", {"mode": "free", "position": {"x": x, "y": y, "z": z}, "yaw": yaw, "pitch": pitch})


out = {}
call("POST", P, {"hide_world": False, "show_preview": False})   # today's store drawn, the preview not
call("POST", "/api/debug/tonemap", {"curve": 0})
call("POST", "/api/debug/foliage", {"windStrength": 0.0})
call("POST", "/api/debug/gi", {"enabled": False})
A, A2 = {}, {}
for n in POSES:
    pose(n)
    A[n] = shot(f"f34_{n}_A.png", 10.0)
    A2[n] = shot(f"f34_{n}_A2.png", 3.0)
t = time.time()
r = call("POST", P, {"source": "world_db", "region": {"from": [-2, 0, -2], "to": [2, 2, 2]}, "hide_world": True})
out["build"] = {k: r.get(k) for k in ("error", "faces", "sprigs", "chunks", "converted", "palette", "build_wall_ms")}
out["build"]["wall_s"] = round(time.time() - t, 1)
print("build", json.dumps({k: v for k, v in out["build"].items() if k != "converted"}), flush=True)
print("converted", json.dumps(out["build"]["converted"]), flush=True)
call("POST", P, {"hide_world": True})
call("POST", P, {"show_preview": True})
B, B2 = {}, {}
for n in POSES:
    pose(n)
    B[n] = shot(f"f34_{n}_B.png", 8.0)
    B2[n] = shot(f"f34_{n}_B2.png", 3.0)
total = (CLEAN[2] - CLEAN[0]) * (CLEAN[3] - CLEAN[1])
out["pixels"] = {}
for n in POSES:
    ab, dm = diff(A[n], B[n])
    out["pixels"][n] = {"A_vs_B_px": ab, "A_vs_B_pct": round(100.0 * ab / total, 2), "A_control_px": diff(A[n], A2[n])[0],
                        "B_control_px": diff(B[n], B2[n])[0]}
    x0, y0, x1, y1 = CLEAN
    vis = (A[n][y0:y1, x0:x1] // 3).astype(np.uint8)
    vis[dm] = [255, 0, 255]
    Image.fromarray(vis).save(os.path.join(HERE, f"f34_{n}_diffmap.png"))
print("pixels", json.dumps(out["pixels"]), flush=True)
call("POST", "/api/debug/tonemap", {"curve": 1})
call("POST", "/api/debug/foliage", {"windStrength": 0.05})
call("POST", "/api/debug/gi", {"enabled": True})
json.dump(out, open(os.path.join(HERE, "voxfound_f34_gate.json"), "w"), indent=1)
print("end", flush=True)

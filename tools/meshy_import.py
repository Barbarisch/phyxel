def import_all(input_path, name, out_dir, spec, source="local-mesh", prompt=None,
               image=None, meshy_info=None, log=print):
    """import_mesh at the primary tier, then at each spec['also_tier'], then the
    reduced GLB copy. Returns the primary result with r['extra'] (list of results),
    r['reduce'] (report or None) and r['outputs'] (every file written)."""
    kw = {k: spec[k] for k in IMPORT_KEYS if spec.get(k) is not None}
    kind = kw.get("kind", "prop")
    r = import_mesh(input_path, name, out_dir=out_dir, source=source, prompt=prompt,
                    image=image, meshy_info=meshy_info, log=log, **kw)
    r["extra"], r["reduce"] = [], None
    for t in spec.get("also_tier") or []:
        t = TIER_ALIASES.get(t, t)
        if t == r["provenance"]["tier"]:
            continue
        kw2 = dict(kw, tier=t, preview=False, compact=None)
        r["extra"].append(import_mesh(input_path, f"{name}_{t}", out_dir=out_dir,
                                      source=source, prompt=prompt, image=image,
                                      meshy_info=meshy_info, log=log, **kw2))
    do_reduce = spec.get("reduce")
    if do_reduce is None:
        do_reduce = kind == "building"
    if do_reduce:
        dest = os.path.join(out_dir, reduced_name(input_path))
        if os.path.abspath(dest) == os.path.abspath(input_path):
            raise ImportError_(f"{input_path} is already a reduced copy")
        r["reduce"] = reduce_glb(input_path, dest, spec.get("reduce_texture") or 1024,
                                 spec.get("reduce_faces") or 50000, log=log)
        r["files"]["reduced_glb"] = dest
    # record the companions in the primary provenance file
    prov = r["provenance"]
    prov["also_tiers"] = [{"tier": x["provenance"]["tier"], "stem": x["stem"]}
                          for x in r["extra"]]
    if r["reduce"]:
        prov["reduced_copy"] = dict(r["reduce"], file=os.path.basename(r["reduce"]["file"]))
    with open(r["files"]["provenance"], "w", encoding="utf-8", newline="\n") as f:
        json.dump(prov, f, indent=2)
    r["outputs"] = list(r["files"].values()) + [p for x in r["extra"]
                                                for p in x["files"].values()]
    return r


def generate_and_import(mode, source_text, name, out_dir, spec, gen_params=None,
                        budget_floor=DEFAULT_BUDGET_FLOOR, ledger_path=None, era=None,
                        log=print):
    """One paid generation + its import, with exactly one ledger line."""
    glb = os.path.join(out_dir, sanitize_stem(name) + ".meshy.glb")
    era = era or spec.get("era") or infer_era(out_dir)
    spec = dict(spec, era=era)
    extra = {"name": sanitize_stem(name), "era": era, "kind": spec.get("kind", "prop"),
             "size_m": spec.get("size"),
             "size_basis": (spec.get("size_basis") or "").strip() or "NOT STATED",
             "note": spec.get("note")}
    info, entry = generate(mode, source_text, glb, gen_params, budget_floor, ledger_path,
                           ledger_extra=extra, log=log)
    if info.get("image"):
        info["image"] = rel_ref(info["image"])
    try:
        r = import_all(glb, name, out_dir, spec, source="meshy",
                       prompt=source_text if mode == "text-to-3d" else None,
                       image=source_text if mode == "image-to-3d" else None,
                       meshy_info=info, log=log)
    except Exception as e:
        entry["status"] = f"generated; IMPORT FAILED: {type(e).__name__}: {e}"[:400]
        _close_ledger_entry(entry, [glb], ledger_path)
        raise
    entry["status"] = "ok"
    _close_ledger_entry(entry, [glb] + r["outputs"], ledger_path)
    r["ledger"] = entry
    return r


MANIFEST_KEYS = {"era", "name", "kind", "tier", "size", "size_axis", "prompt", "image",
                 "map", "default_material", "also_tier", "clusters", "preview", "reduce",
                 "note", "size_basis", "keep_islands", "island_fraction"} | set(gen_defaults())


def _manifest_entries(manifest_path):
    doc = json.load(open(manifest_path, encoding="utf-8"))
    entries = doc if isinstance(doc, list) else doc.get("entries")
    defaults = {} if isinstance(doc, list) else (doc.get("defaults") or {})
    if not isinstance(entries, list) or not entries:
        raise ImportError_(f"{manifest_path}: no entries")
    out, seen = [], set()
    for i, raw in enumerate(entries):
        e = {**defaults, **raw}
        unknown = set(e) - MANIFEST_KEYS
        if unknown:
            raise ImportError_(f"{manifest_path} entry {i}: unknown keys {sorted(unknown)}")
        for k in ("era", "name", "kind", "size"):
            if e.get(k) in (None, ""):
                raise ImportError_(f"{manifest_path} entry {i}: '{k}' is required")
        if bool(e.get("prompt")) == bool(e.get("image")):
            raise ImportError_(f"{manifest_path} entry {i} ({e['name']}): give exactly one "
                               f"of 'prompt' or 'image'")
        if e["kind"] not in KIND_DEFAULT_TIER:
            raise ImportError_(f"{manifest_path} entry {i}: kind '{e['kind']}'")
        if not isinstance(e["size"], (int, float)) or e["size"] <= 0:
            raise ImportError_(f"{manifest_path} entry {i}: size must be a number > 0")
        if e.get("image") and not re.match(r"^https?://", e["image"]):
            img = e["image"]
            if not os.path.isabs(img):
                near = os.path.join(os.path.dirname(os.path.abspath(manifest_path)), img)
                img = near if os.path.exists(near) else os.path.join(ROOT, img)
            e["image"] = img
        key = (sanitize_stem(e["era"]), sanitize_stem(e["name"]))
        if key in seen:
            raise ImportError_(f"{manifest_path} entry {i}: duplicate era/name {key}")
        seen.add(key)
        out.append(e)
    return out


def run_batch(manifest_path, ref_root=None, budget_floor=DEFAULT_BUDGET_FLOOR,
              ledger_path=None, dry_run=False, log=print):
    """Generate every manifest entry that has no provenance file yet, one at a time,
    into <ref_root>/<era>/. Stops cleanly at the budget floor and at the first
    failure (a failure can have spent credits). Returns a summary dict."""
    ref_root = ref_root or MESHY_REF_ROOT
    entries = _manifest_entries(manifest_path)
    summary = {"done": [], "skipped": [], "planned": [], "failed": None, "stopped": None,
               "remaining": []}
    for i, e in enumerate(entries):
        era, name = sanitize_stem(e["era"]), sanitize_stem(e["name"])
        out_dir = os.path.join(ref_root, era)
        stem = ("meshyref_" if e["kind"] == "building" else "meshy_") + name
        if os.path.exists(os.path.join(out_dir, stem + ".provenance.json")):
            log(f"[batch] {era}/{name}: provenance exists - skipped")
            summary["skipped"].append(f"{era}/{name}")
            continue
        mode = "text-to-3d" if e.get("prompt") else "image-to-3d"
        gen = {k: e[k] for k in gen_defaults() if k in e}
        est = estimate_credits(mode, {**gen_defaults(), **gen})
        if dry_run:
            log(f"[batch] {era}/{name}: would generate ({mode}, {gen.get('ai_model', 'latest')}"
                f", estimated {est} credits) -> {repo_rel(out_dir)}")
            summary["planned"].append({"entry": f"{era}/{name}", "mode": mode,
                                       "estimated_credits": est})
            continue
        spec = {"kind": e["kind"], "tier": e.get("tier"), "size": e["size"],
                "size_axis": e.get("size_axis", "y"), "map_overrides": e.get("map") or {},
                "default_material": e.get("default_material"),
                "also_tier": e.get("also_tier") or [], "clusters": e.get("clusters"),
                "preview": e.get("preview", True), "reduce": e.get("reduce"),
                "note": e.get("note"), "size_basis": e.get("size_basis"),
                "keep_islands": e.get("keep_islands"),
                "island_fraction": e.get("island_fraction")}
        log(f"[batch] {era}/{name}: generating ({mode}, estimated {est} credits)")
        try:
            r = generate_and_import(mode, e.get("prompt") or e["image"], name, out_dir, spec,
                                    gen, budget_floor, ledger_path, era=era, log=log)
        except BudgetStop as stop:
            summary["stopped"] = str(stop)
            summary["remaining"] = [f"{sanitize_stem(x['era'])}/{sanitize_stem(x['name'])}"
                                    for x in entries[i:]]
            log(f"[batch] STOPPED at the budget floor: {stop}")
            break
        except ImportError_ as err:
            summary["failed"] = {"entry": f"{era}/{name}", "error": str(err)}
            summary["remaining"] = [f"{sanitize_stem(x['era'])}/{sanitize_stem(x['name'])}"
                                    for x in entries[i + 1:]]
            log(f"[batch] FAILED {era}/{name}: {err} - batch stopped")
            break
        summary["done"].append({"entry": f"{era}/{name}", "credits": r["ledger"]["credits"],
                                "balance_after": r["ledger"]["balance_after"]})
        log(f"[batch] {era}/{name}: done, {r['ledger']['credits']} credits, balance "
            f"{r['ledger']['balance_after']}")
    return summary



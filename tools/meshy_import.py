def parse_map_string(s):
    out = {}
    if not s:
        return out
    for tok in s.split(","):
        k, _, v = tok.partition("=")
        k, v = k.strip(), v.strip()
        if k and v:
            out[k] = v
    return out


def map_clusters(clusters, table, overrides, default_material, all_names,
                 metric="rgb", role_tables=None):
    """Fill cluster['material'] / ['how'] / ['tint']. overrides: {"<id>"|"#hex": Mat}.
    role_tables: {"roof": table, "wall": table} - a cluster carrying c['role'] is
    matched within that role's table (buildings); otherwise within `table`."""
    by_id, by_hex = {}, []
    for k, v in overrides.items():
        if v not in all_names:
            raise ImportError_(f"override '{k}={v}': '{v}' is not a material in "
                               f"materials.json (names are case-sensitive)")
        if k.startswith("#"):
            by_hex.append((parse_hex(k), v))
        else:
            by_id[int(k)] = v
    if default_material and default_material not in all_names:
        raise ImportError_(f"--default-material '{default_material}' is not in materials.json")
    coloured = [c for c in clusters if c["coloured"]]
    for rgb, v in by_hex:      # a hex override claims the nearest coloured cluster
        if not coloured:
            continue
        c = min(coloured, key=lambda c: sum((a - b) ** 2 for a, b in zip(c["rgb"], rgb)))
        by_id.setdefault(c["id"], v)
    for c in clusters:
        if c["id"] in by_id:
            c["material"], c["how"] = by_id[c["id"]], "override"
        elif not c["coloured"]:
            if not default_material:
                raise ImportError_(
                    "the mesh (or part of it) carries no texture / vertex colour, so there "
                    "is nothing to map by colour. Pass --default-material <Name> (or "
                    f"--map \"{c['id']}=<Name>\") - the tool will not pick one for you.")
            c["material"], c["how"] = default_material, "default-material (no colour in mesh)"
        else:
            role = c.get("role")
            tbl = (role_tables or {}).get(role) or table
            name, d = nearest_material(c["rgb"], tbl, metric)
            c["material"] = name
            c["how"] = (f"nearest {role + ' ' if role and role_tables else ''}colour "
                        f"({metric} distance {d:.0f})")
            c["distance"] = round(float(d), 1)
            if d > WEAK_MATCH[metric]:
                c["how"] += " WEAK - no close material, use --map"
        c["tint"] = hex_of(c["rgb"]) if c["coloured"] else None
    return clusters



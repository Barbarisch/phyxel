def view_labels(grid):
    """front (x right, y up, seen from +Z), side (z right, y up, seen from +X),
    top (x right, z down, seen from +Y). Each a 2D int array, -1 empty, row 0 = top."""
    def first_hit(g, axis):       # nearest cell from the + side of axis
        occ = g >= 0
        rev = np.flip(g, axis=axis)
        i = np.argmax(np.flip(occ, axis=axis), axis=axis)
        lab = np.take_along_axis(rev, np.expand_dims(i, axis), axis=axis).squeeze(axis)
        return np.where(occ.any(axis=axis), lab, -1)
    front = first_hit(grid, 2)            # (x,y)
    side = first_hit(grid, 0)             # (y,z)
    top = first_hit(grid, 1)              # (x,z)
    return {
        "front": np.flipud(front.T),              # rows = y descending, cols = x
        "side": np.flipud(side),                  # rows = y descending, cols = z
        "top": top.T,                             # rows = z, cols = x
    }


def ascii_preview(grid, clusters, max_cols=72):
    out = []
    views = view_labels(grid)
    for name in ("front", "side", "top"):
        v = views[name]
        f = max(1, math.ceil(v.shape[1] / max_cols))
        out.append(f"--- {name} ({v.shape[1]} x {v.shape[0]} cells"
                   + (f", shown 1:{f}" if f > 1 else "") + ") ---")
        for r in range(0, v.shape[0], f):
            row = []
            for c in range(0, v.shape[1], f):
                blk = v[r:r + f, c:c + f]
                blk = blk[blk >= 0]
                row.append(chr(ord("A") + int(np.bincount(blk).argmax()) % 26) if blk.size else ".")
            out.append("".join(row))
    out.append("legend: " + ", ".join(
        f"{chr(ord('A') + c['id'] % 26)}={c['material']}" for c in clusters) + ", .=empty")
    return "\n".join(out)


def png_preview(grid, clusters, path, title):
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        return False
    views = view_labels(grid)
    pal = [tuple(c["rgb"]) if c["coloured"] else (150, 150, 150) for c in clusters]
    widest = sum(v.shape[1] for v in views.values())
    s = int(max(1, min(10, 1100 // max(1, widest))))
    gap, top_pad = 16, 34
    H = max(v.shape[0] for v in views.values()) * s + top_pad + 8
    W = widest * s + gap * 4
    im = Image.new("RGB", (W, H), (245, 245, 245))
    d = ImageDraw.Draw(im)
    d.text((gap, 4), title, fill=(0, 0, 0))
    x0 = gap
    for name in ("front", "side", "top"):
        v = views[name]
        rgb = np.full(v.shape + (3,), 245, np.uint8)
        for i, colour in enumerate(pal):
            rgb[v == i] = colour
        tile = Image.fromarray(rgb).resize((v.shape[1] * s, v.shape[0] * s), Image.NEAREST)
        im.paste(tile, (x0, top_pad))
        d.text((x0, 19), f"{name} {v.shape[1]}x{v.shape[0]}", fill=(60, 60, 60))
        x0 += v.shape[1] * s + gap
    im.save(path)
    return True



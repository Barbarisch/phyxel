def emit_lines(grid, clusters, tier, emit_tint, compact):
    """Template body lines. compact: 'none' | 'sub' (uniform 3^3 -> S) | 'cube'
    (also uniform 9^3 / 3^3 -> C)."""
    def app(lab):
        c = clusters[lab]
        s = c["material"]
        if emit_tint and c["tint"]:
            s += f" tint={c['tint']}"
        return s

    lines = []
    counts = {"C": 0, "S": 0, "M": 0, "V": 0}
    xs, ys, zs = np.nonzero(grid >= 0)
    if tier == "fine":
        order = np.lexsort((zs, ys, xs))
        for i in order:
            lines.append(f"V {xs[i]} {ys[i]} {zs[i]} {app(int(grid[xs[i], ys[i], zs[i]]))}")
        counts["V"] = len(lines)
        return lines, counts

    res = TIER_RES[tier]            # 9 or 3
    pad = [(0, (-d) % res) for d in grid.shape]
    g = np.pad(grid, pad, constant_values=-1)
    X, Y, Z = (d // res for d in g.shape)
    blocks = g.reshape(X, res, Y, res, Z, res).transpose(0, 2, 4, 1, 3, 5)
    for cx in range(X):
        for cy in range(Y):
            for cz in range(Z):
                b = blocks[cx, cy, cz]
                if (b < 0).all():
                    continue
                if compact == "cube" and b.min() >= 0 and b.min() == b.max():
                    lines.append(f"C {cx} {cy} {cz}  {app(int(b[0, 0, 0]))}")
                    counts["C"] += 1
                    continue
                if tier == "subcube":
                    for sx in range(3):
                        for sy in range(3):
                            for sz in range(3):
                                v = int(b[sx, sy, sz])
                                if v >= 0:
                                    lines.append(f"S {cx} {cy} {cz}  {sx} {sy} {sz}  {app(v)}")
                                    counts["S"] += 1
                    continue
                for sx in range(3):
                    for sy in range(3):
                        for sz in range(3):
                            sb = b[sx * 3:sx * 3 + 3, sy * 3:sy * 3 + 3, sz * 3:sz * 3 + 3]
                            if (sb < 0).all():
                                continue
                            if compact in ("sub", "cube") and sb.min() >= 0 and sb.min() == sb.max():
                                lines.append(f"S {cx} {cy} {cz}  {sx} {sy} {sz}  {app(int(sb[0, 0, 0]))}")
                                counts["S"] += 1
                                continue
                            for mx in range(3):
                                for my in range(3):
                                    for mz in range(3):
                                        v = int(sb[mx, my, mz])
                                        if v >= 0:
                                            lines.append(
                                                f"M {cx} {cy} {cz}  {sx} {sy} {sz}  "
                                                f"{mx} {my} {mz}  {app(v)}")
                                            counts["M"] += 1
    return lines, counts


def read_voxel_file(path):
    """Parse a .voxel file (the C/S/M/V grammar vox_import.py / gen_items.py write
    and ObjectTemplateManager::parseLine reads) into
    dict(grid_res, cells {(x,y,z) at the file's finest lattice: material},
         counts, tints {material: set}).
    The lattice is the `# grid:` value for V files, 9 cells per cube otherwise."""
    counts = {"C": 0, "S": 0, "M": 0, "V": 0}
    grid_res = None
    raw = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            if line.startswith("#"):
                if line.startswith("# grid:"):
                    grid_res = int(line.split(":", 1)[1])
                continue
            p = line.split()
            kind = p[0]
            if kind not in counts:
                raise ValueError(f"{path}: unknown line kind '{kind}'")
            nint = {"C": 3, "S": 6, "M": 9, "V": 3}[kind]
            ints = [int(v) for v in p[1:1 + nint]]
            mat = p[1 + nint]
            extras = p[2 + nint:]
            for e in extras:
                if not (e.startswith("tint=#") and len(e) == 12) and not e.startswith("state="):
                    raise ValueError(f"{path}: bad trailing token '{e}'")
            counts[kind] += 1
            raw.append((kind, ints, mat))
    if counts["V"] and (counts["C"] or counts["S"] or counts["M"]):
        raise ValueError(f"{path}: V lines mixed with C/S/M (one lattice per file)")
    if counts["V"] and grid_res not in (27, 81):
        raise ValueError(f"{path}: V lines need '# grid: 27|81' (got {grid_res})")
    cells = {}
    lattice = grid_res if counts["V"] else 9
    for kind, i, mat in raw:
        if kind == "V":
            cells[(i[0], i[1], i[2])] = mat
        elif kind == "C":
            for dx in range(9):
                for dy in range(9):
                    for dz in range(9):
                        cells[(i[0] * 9 + dx, i[1] * 9 + dy, i[2] * 9 + dz)] = mat
        elif kind == "S":
            if not all(0 <= v <= 2 for v in i[3:6]):
                raise ValueError(f"{path}: S sub-index out of 0..2")
            for dx in range(3):
                for dy in range(3):
                    for dz in range(3):
                        cells[(i[0] * 9 + i[3] * 3 + dx, i[1] * 9 + i[4] * 3 + dy,
                               i[2] * 9 + i[5] * 3 + dz)] = mat
        else:
            if not all(0 <= v <= 2 for v in i[3:9]):
                raise ValueError(f"{path}: M sub/micro index out of 0..2")
            cells[(i[0] * 9 + i[3] * 3 + i[6], i[1] * 9 + i[4] * 3 + i[7],
                   i[2] * 9 + i[5] * 3 + i[8])] = mat
    return {"grid_res": lattice, "cells": cells, "counts": counts}


def extent_cells(cells):
    """(w,h,d) of the occupied bounding box in lattice cells."""
    a = np.array(list(cells))
    return tuple(int(v) for v in (a.max(axis=0) - a.min(axis=0) + 1))



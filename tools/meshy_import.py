def load_material_names(path=MATERIALS_JSON):
    doc = json.load(open(path, encoding="utf-8"))
    return {m["name"] for m in doc["materials"] if isinstance(m, dict)}


def load_material_table(path=MATERIALS_JSON, color_table="tint",
                        only=None, exclude=None):
    """[(name, (r,g,b) 0..255)] of nearest-colour candidates.

    color_table "tint":    materials.json physics.colorTint (vox_import.py's table)
    color_table "texture": mean colour of the material's side_n source texture
                           (falls back to colorTint when the PNG is missing)
    """
    doc = json.load(open(path, encoding="utf-8"))
    out = []
    for m in doc["materials"]:
        if not isinstance(m, dict):
            continue
        name = m["name"]
        if only:
            if name not in only:
                continue
        else:
            if m.get("category") != "material" or name.startswith("vox_"):
                continue
            if name in NEVER_CANDIDATES or (exclude and name in exclude):
                continue
        tint = m.get("physics", {}).get("colorTint")
        rgb = tuple(int(round(c * 255)) for c in tint[:3]) if tint else None
        if color_table == "texture":
            tex = m.get("textures", {}).get("side_n")
            p = os.path.join(TEXTURE_SRC, tex) if tex else None
            if p and os.path.exists(p):
                from PIL import Image
                im = Image.open(p).convert("RGB").resize((16, 16))
                rgb = tuple(int(round(v)) for v in
                            np.asarray(im, dtype=np.float64).reshape(-1, 3).mean(axis=0))
        if rgb is None:
            continue
        out.append((name, rgb))
    if not out:
        raise ImportError_("no candidate materials (check --only-materials / --exclude)")
    if isinstance(only, (list, tuple)):          # an ordered list sets the tie-break order
        out.sort(key=lambda t: only.index(t[0]))
    return out


def building_material_sets(path=MATERIALS_JSON, log=None):
    """(wall names, roof names) of the building candidate set that exist in
    materials.json, in tie-break order."""
    names = load_material_names(path)
    walls = [n for n in BUILDING_WALL_MATERIALS if n in names]
    roofs = [n for n in BUILDING_ROOF_MATERIALS if n in names]
    missing = [n for n in BUILDING_WALL_MATERIALS + BUILDING_ROOF_MATERIALS if n not in names]
    if missing and log:
        log(f"[meshy_import] building material set: not in materials.json, dropped: {missing}")
    return walls, roofs


def colour_distance(a, b, metric="rgb"):
    """rgb: plain Euclidean RGB distance. chroma: lightness at half weight, the two
    opponent axes (r-g, yellow-blue) at full weight - baked light and shade in a
    generated texture move lightness far more than hue."""
    if metric == "rgb":
        return math.sqrt(sum((x - y) ** 2 for x, y in zip(a, b)))
    dl = (sum(a) - sum(b)) / 3.0
    d1 = (a[0] - a[1]) - (b[0] - b[1])
    d2 = ((a[0] + a[1]) / 2.0 - a[2]) - ((b[0] + b[1]) / 2.0 - b[2])
    return math.sqrt((0.5 * dl) ** 2 + d1 ** 2 + d2 ** 2)


def nearest_material(rgb, table, metric="rgb"):
    best, bestd = None, None
    for name, cand in table:
        d = colour_distance(rgb, cand, metric)
        if bestd is None or d < bestd:
            best, bestd = name, d
    return best, bestd


def hex_of(rgb):
    return "#%02x%02x%02x" % tuple(int(max(0, min(255, round(v)))) for v in rgb)


def parse_hex(s):
    s = s.lstrip("#")
    return (int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16))



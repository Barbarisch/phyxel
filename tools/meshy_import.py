def register(voxel_path, library_root=None, log=print):
    """Copy <stem>.voxel (+ provenance/massing sidecars) into
    <library>/generated/, seed the catalog entry's intent fields, regenerate the
    catalog with tools/asset_index.py's own build_index(), and add `source` +
    `provenance` to the entry. Returns the catalog entry."""
    sys.path.insert(0, TOOLS_DIR)
    import asset_index as ai
    if library_root:
        ai.TPL = library_root
        ai.CATALOG = os.path.join(library_root, "template_catalog.json")
        ai.ITEMS_MANIFEST = os.path.join(library_root, "items_manifest.json")
        ai.ITEMS_JSON = os.path.join(library_root, "items.json")   # usually absent
    stem = os.path.basename(voxel_path)[:-len(".voxel")]
    prov_path = voxel_path[:-len(".voxel")] + ".provenance.json"
    if not os.path.exists(prov_path):
        raise ImportError_(f"{prov_path} not found - register only what this tool wrote")
    prov = json.load(open(prov_path, encoding="utf-8"))
    existing = library_stems(ai.TPL)
    if stem in existing:
        raise ImportError_(f"stem '{stem}' already in the library ({existing[stem]})")
    dest_dir = os.path.join(ai.TPL, "generated")
    os.makedirs(dest_dir, exist_ok=True)
    for suffix in (".voxel", ".provenance.json", ".massing.json"):
        src = voxel_path[:-len(".voxel")] + suffix
        if os.path.exists(src):
            shutil.copy2(src, os.path.join(dest_dir, stem + suffix))

    catalog = {}
    if os.path.exists(ai.CATALOG):
        catalog = json.load(open(ai.CATALOG, encoding="utf-8"))
    catalog[stem] = dict(prov["catalog_intent"])
    with open(ai.CATALOG, "w", newline="\n", encoding="utf-8") as f:
        json.dump(catalog, f, indent=2, sort_keys=True)

    catalog, problems = ai.build_index()
    catalog[stem]["source"] = prov["source"]
    catalog[stem]["provenance"] = f"generated/{stem}.provenance.json"
    with open(ai.CATALOG, "w", newline="\n", encoding="utf-8") as f:
        json.dump(catalog, f, indent=2, sort_keys=True)
    for p in problems:
        log(f"  PROBLEM: {p}")
    log(f"registered {stem} -> {os.path.join(dest_dir, stem + '.voxel')}; catalog has "
        f"{len(catalog)} templates, {len(problems)} problems")
    return catalog[stem], problems



def meshy_text_to_3d(prompt, dest_glb, params=None, log=print, ids_out=None):
    """preview task -> (optional) refine task for the texture -> GLB. Task ids are
    appended to ids_out as they are created (so a failure still records them)."""
    p = {**gen_defaults(), **(params or {})}
    ids = ids_out if ids_out is not None else []
    if len(prompt) > 800:
        raise ImportError_(f"prompt is {len(prompt)} characters; Meshy accepts up to 800")
    body = {"mode": "preview", "prompt": prompt, "ai_model": p["ai_model"],
            "target_formats": ["glb"], **_remesh_fields(p)}
    tid = _meshy_create(TEXT_PATH, body)
    ids.append(tid)
    task = _meshy_wait(TEXT_PATH, tid, log=log)
    reported = task.get("consumed_credits") or 0
    if p["texture"]:
        rid = _meshy_create(TEXT_PATH, {"mode": "refine", "preview_task_id": tid,
                                        "target_formats": ["glb"], **_texture_fields(p)})
        ids.append(rid)
        task = _meshy_wait(TEXT_PATH, rid, log=log)
        reported += task.get("consumed_credits") or 0
    _meshy_download(task, dest_glb)
    return {"mode": "text-to-3d", "task_ids": list(ids), "prompt": prompt,
            "ai_model": p["ai_model"], "consumed_credits": reported}


def meshy_image_to_3d(image, dest_glb, params=None, log=print, ids_out=None):
    """`image` is a public URL or a local JPG/PNG/WebP (sent as a data URI).
    Run once against the service (2026-11-21, local JPG, default parameters)."""
    p = {**gen_defaults(), **(params or {})}
    ids = ids_out if ids_out is not None else []
    if re.match(r"^https?://", image):
        image_url = image
    else:
        ext = os.path.splitext(image)[1].lower().lstrip(".")
        mime = {"jpg": "image/jpeg", "jpeg": "image/jpeg", "png": "image/png",
                "webp": "image/webp"}.get(ext)
        if not mime:
            raise ImportError_(f"{image}: Meshy accepts JPG, PNG or WebP")
        if not os.path.exists(image):
            raise ImportError_(f"{image}: no such image file")
        with open(image, "rb") as f:
            image_url = f"data:{mime};base64," + base64.b64encode(f.read()).decode("ascii")
    body = {"image_url": image_url, "ai_model": p["ai_model"],
            "should_texture": bool(p["texture"]), "target_formats": ["glb"],
            **_remesh_fields(p)}
    if p["texture"]:
        body.update(_texture_fields(p))
    tid = _meshy_create(IMAGE_PATH, body)
    ids.append(tid)
    task = _meshy_wait(IMAGE_PATH, tid, log=log)
    _meshy_download(task, dest_glb)
    return {"mode": "image-to-3d", "task_ids": list(ids), "image": image,
            "ai_model": p["ai_model"], "consumed_credits": task.get("consumed_credits")}



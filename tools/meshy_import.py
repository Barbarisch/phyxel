def generate(mode, source_text, dest_glb, params=None, budget_floor=DEFAULT_BUDGET_FLOOR,
             ledger_path=None, ledger_extra=None, log=print):
    """One paid generation: balance check against the floor, the call, the balance
    again. Returns (meshy_info, ledger_entry). The caller adds the output files and
    calls append_ledger(entry) - or use generate_and_import, which does. On a
    failure after the balance check this appends the ledger line itself."""
    p = {**gen_defaults(), **(params or {})}
    est = estimate_credits(mode, p)
    before = meshy_balance()
    if before - est < budget_floor:
        raise BudgetStop(f"balance {before} - estimated {est} credits = {before - est} is "
                         f"below the budget floor {budget_floor}; nothing was generated")
    os.makedirs(os.path.dirname(os.path.abspath(dest_glb)), exist_ok=True)
    entry = {
        "when": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
        "mode": mode + (" (preview + refine)" if mode == "text-to-3d" and p["texture"] else ""),
        **(ledger_extra or {}),
        ("prompt" if mode == "text-to-3d" else "image"):
            source_text if mode == "text-to-3d" else rel_ref(source_text),
        "ai_model": p["ai_model"],
        "params": {k: v for k, v in p.items() if k != "ai_model"},
        "estimated_credits": est,
        "task_ids": [],
        "balance_before": before,
    }
    try:
        fn = meshy_text_to_3d if mode == "text-to-3d" else meshy_image_to_3d
        info = fn(source_text, dest_glb, p, log=log, ids_out=entry["task_ids"])
        entry["status"] = "generated"
        entry["consumed_credits_reported"] = info.get("consumed_credits")
    except Exception as e:
        entry["status"] = f"FAILED: {type(e).__name__}: {e}"[:400]
        _close_ledger_entry(entry, [], ledger_path)
        raise
    return info, entry


def _close_ledger_entry(entry, outputs, ledger_path):
    try:
        entry["balance_after"] = meshy_balance()
        entry["credits"] = entry["balance_before"] - entry["balance_after"]
    except Exception as e:                      # the line is still written
        entry["balance_after"] = None
        entry["credits"] = None
        entry["balance_error"] = str(e)[:200]
    entry["outputs"] = [repo_rel(o) for o in outputs]
    append_ledger(entry, ledger_path)



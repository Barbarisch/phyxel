def _cluster_faces(V, F, cell):
    """Vertex clustering on a `cell` grid. Returns (sinv vertex->cluster, n clusters,
    kept face indices: non-degenerate, one per distinct cluster triple)."""
    lo = V.min(axis=0)
    q = np.floor((V - lo) / cell).astype(np.int64)
    d = q.max(axis=0) + 1
    key = (q[:, 0] * d[1] + q[:, 1]) * d[2] + q[:, 2]
    _, sinv = np.unique(key, return_inverse=True)
    sinv = sinv.reshape(-1)
    fs = sinv[F]
    ok = np.nonzero((fs[:, 0] != fs[:, 1]) & (fs[:, 1] != fs[:, 2]) & (fs[:, 0] != fs[:, 2]))[0]
    srt = np.sort(fs[ok], axis=1)
    order = np.lexsort((srt[:, 2], srt[:, 1], srt[:, 0]))
    srt = srt[order]
    first = np.r_[True, (srt[1:] != srt[:-1]).any(axis=1)] if len(srt) else np.zeros(0, bool)
    return sinv, int(sinv.max()) + 1, ok[order][first]


def decimate_clustering(V, F, UV=None, VC=None, max_faces=50000):
    """Reduce a triangle mesh to at most max_faces by vertex clustering (numpy only;
    cruder than quadric decimation: silhouettes get stair-stepped at the cell size).
    Vertices in one grid cell collapse to their mean position; a cell's vertices
    that sit in different parts of the texture keep separate UVs (same position),
    so texture seams survive. Returns (V, F, UV, VC, cell_size or None)."""
    if len(F) <= max_faces:
        return V, F, UV, VC, None
    diag = float(np.linalg.norm(V.max(axis=0) - V.min(axis=0)))
    lo_c, hi_c = diag / 4096.0, diag / 8.0
    best = None
    for _ in range(14):                      # bisection on the cell size (log scale)
        mid = math.sqrt(lo_c * hi_c)
        sinv, ns, keep = _cluster_faces(V, F, mid)
        if len(keep) <= max_faces:
            best, hi_c = (mid, sinv, ns, keep), mid
        else:
            lo_c = mid
    if best is None:
        best = (hi_c,) + _cluster_faces(V, F, hi_c)
    cell, sinv, ns, keep = best
    cnt = np.bincount(sinv, minlength=ns).astype(np.float64)
    P = np.stack([np.bincount(sinv, weights=V[:, i], minlength=ns) / cnt for i in range(3)], 1)
    Fk = F[keep]
    if UV is None:
        C = None
        if VC is not None:
            C = np.stack([np.bincount(sinv, weights=VC[:, i].astype(np.float64), minlength=ns)
                          / cnt for i in range(VC.shape[1])], 1)
        return P, sinv[Fk], None, C, cell
    uq = np.floor(UV * 32.0).astype(np.int64)        # 1/32 of the texture = "same part"
    uq -= uq.min(axis=0)
    du = uq.max(axis=0) + 1
    key = (sinv * du[0] + uq[:, 0]) * du[1] + uq[:, 1]
    used = np.unique(Fk)
    uk, inv_used = np.unique(key[used], return_inverse=True)
    inv_used = inv_used.reshape(-1)
    vmap = np.full(len(V), -1, np.int64)
    vmap[used] = inv_used
    n2 = len(uk)
    c2 = np.bincount(inv_used, minlength=n2).astype(np.float64)
    UV2 = np.stack([np.bincount(inv_used, weights=UV[used, i], minlength=n2) / c2
                    for i in range(2)], 1)
    owner = np.zeros(n2, np.int64)
    owner[inv_used] = sinv[used]
    return P[owner], vmap[Fk], UV2, None, cell


def _shrink_image(img, max_edge, jpeg_quality):
    """(bytes, mime, (w,h)) - downscaled to max_edge; JPEG unless the image has alpha."""
    import io
    from PIL import Image
    has_alpha = img.mode in ("RGBA", "LA", "PA") or "transparency" in getattr(img, "info", {})
    if has_alpha:
        img = img.convert("RGBA")
        if np.asarray(img)[..., 3].min() == 255:
            has_alpha = False
    if not has_alpha:
        img = img.convert("RGB")
    w, h = img.size
    if max(w, h) > max_edge:
        f = max_edge / float(max(w, h))
        img = img.resize((max(1, int(round(w * f))), max(1, int(round(h * f)))), Image.LANCZOS)
    buf = io.BytesIO()
    if has_alpha:
        img.save(buf, format="PNG", optimize=True)
        return buf.getvalue(), "image/png", img.size
    img.save(buf, format="JPEG", quality=jpeg_quality, optimize=True)
    return buf.getvalue(), "image/jpeg", img.size


def write_glb(path, prims):
    """Minimal GLB 2.0 writer. prims: [{P (n,3), F (m,3), UV (n,2)|None (glTF
    convention, v down), VC (n,3|4) 0..255|None, material: {base_color_factor,
    metallic, roughness, double_sided, alpha_mode, textures: {slot: (bytes, mime)}}}].
    No NORMAL attribute is written (a viewer then shades flat, per the glTF spec)."""
    import struct
    bin_parts, views, accessors, images, textures, materials, meshes, nodes = \
        [], [], [], [], [], [], [], []
    offset = 0

    def add_view(data, target=None):
        nonlocal offset
        pad = (-len(data)) % 4
        v = {"buffer": 0, "byteOffset": offset, "byteLength": len(data)}
        if target:
            v["target"] = target
        views.append(v)
        bin_parts.append(data + b"\x00" * pad)
        offset += len(data) + pad
        return len(views) - 1

    def add_accessor(arr, ctype, atype, target, minmax=False, normalized=False):
        a = {"bufferView": add_view(arr.tobytes(), target), "componentType": ctype,
             "count": int(arr.shape[0]) if arr.ndim > 1 else int(arr.size), "type": atype}
        if minmax:
            a["min"] = [float(v) for v in arr.min(axis=0)]
            a["max"] = [float(v) for v in arr.max(axis=0)]
        if normalized:
            a["normalized"] = True
        accessors.append(a)
        return len(accessors) - 1

    for pr in prims:
        attrs = {"POSITION": add_accessor(np.ascontiguousarray(pr["P"], np.float32),
                                          5126, "VEC3", 34962, minmax=True)}
        if pr.get("UV") is not None:
            attrs["TEXCOORD_0"] = add_accessor(np.ascontiguousarray(pr["UV"], np.float32),
                                               5126, "VEC2", 34962)
        if pr.get("VC") is not None:
            vc = np.asarray(pr["VC"])
            if vc.shape[1] == 3:
                vc = np.c_[vc, np.full(len(vc), 255)]
            attrs["COLOR_0"] = add_accessor(
                np.ascontiguousarray(np.clip(np.round(vc), 0, 255), np.uint8),
                5121, "VEC4", 34962, normalized=True)
        n = len(pr["P"])
        idx = np.ascontiguousarray(pr["F"], np.uint16 if n <= 65535 else np.uint32).reshape(-1)
        ind = add_accessor(idx, 5123 if n <= 65535 else 5125, "SCALAR", 34963)
        m = pr.get("material") or {}
        pbr = {"baseColorFactor": [float(v) for v in m.get("base_color_factor", [1, 1, 1, 1])],
               "metallicFactor": float(m.get("metallic", 0.0)),
               "roughnessFactor": float(m.get("roughness", 1.0))}
        mat = {"pbrMetallicRoughness": pbr, "doubleSided": bool(m.get("double_sided", True)),
               "alphaMode": m.get("alpha_mode") or "OPAQUE"}
        for slot, (data, mime) in (m.get("textures") or {}).items():
            images.append({"bufferView": add_view(data), "mimeType": mime})
            textures.append({"source": len(images) - 1})
            ref = {"index": len(textures) - 1}
            if slot in ("baseColorTexture", "metallicRoughnessTexture"):
                pbr[slot] = ref
            else:
                mat[slot] = ref
        materials.append(mat)
        meshes.append({"primitives": [{"attributes": attrs, "indices": ind, "mode": 4,
                                       "material": len(materials) - 1}]})
        nodes.append({"mesh": len(meshes) - 1})
    doc = {"asset": {"version": "2.0", "generator": "phyxel tools/meshy_import.py --reduce"},
           "scene": 0, "scenes": [{"nodes": list(range(len(nodes)))}], "nodes": nodes,
           "meshes": meshes, "materials": materials, "accessors": accessors,
           "bufferViews": views, "buffers": [{"byteLength": offset}]}
    if images:
        doc["images"], doc["textures"] = images, textures
    js = json.dumps(doc, separators=(",", ":")).encode("utf-8")
    js += b" " * ((-len(js)) % 4)
    blob = b"".join(bin_parts)
    with open(path, "wb") as f:
        f.write(struct.pack("<III", 0x46546C67, 2, 12 + 8 + len(js) + 8 + len(blob)))
        f.write(struct.pack("<II", len(js), 0x4E4F534A) + js)
        f.write(struct.pack("<II", len(blob), 0x004E4942) + blob)
    return path


TEXTURE_SLOTS = ("baseColorTexture", "metallicRoughnessTexture", "normalTexture",
                 "occlusionTexture", "emissiveTexture")


def reduce_glb(src, dest, max_texture=1024, max_faces=50000, jpeg_quality=85, log=print):
    """Write a small copy of a mesh file as GLB: every texture downscaled to
    max_texture on its longer edge (JPEG where there is no alpha), geometry
    decimated to about max_faces in total by vertex clustering, normals dropped.
    Returns a report dict. The ORIGINAL is what gets voxelized, never this copy."""
    import trimesh
    loaded = trimesh.load(src, process=False)
    parts = loaded.dump(concatenate=False) if isinstance(loaded, trimesh.Scene) else [loaded]
    parts = [p for p in parts if isinstance(p, trimesh.Trimesh) and len(p.faces)]
    if not parts:
        raise ImportError_(f"{src}: no triangle geometry found")
    total = sum(len(p.faces) for p in parts)
    prims, tex_report, cells = [], [], []
    for part in parts:
        budget = max(100, int(round(max_faces * len(part.faces) / float(total))))
        V = np.asarray(part.vertices, np.float64)
        F = np.asarray(part.faces, np.int64)
        vis = part.visual
        UV = VC = None
        material = {"textures": {}}
        if getattr(vis, "kind", None) == "texture":
            uv = getattr(vis, "uv", None)
            if uv is not None and len(uv) == len(V):
                UV = np.asarray(uv, np.float64)
            mat = getattr(vis, "material", None)
            fac = getattr(mat, "baseColorFactor", None)
            if fac is None:
                fac = getattr(mat, "diffuse", None)
            if fac is not None:
                fac = np.asarray(fac, np.float64).ravel()
                fac = fac / 255.0 if fac.max() > 1.0 else fac
                material["base_color_factor"] = list(fac[:4]) + [1.0] * (4 - len(fac[:4]))
            for k_src, k_dst in (("metallicFactor", "metallic"), ("roughnessFactor", "roughness")):
                v = getattr(mat, k_src, None)
                if v is not None:
                    material[k_dst] = float(v)
            ds = getattr(mat, "doubleSided", None)
            material["double_sided"] = True if ds is None else bool(ds)
            material["alpha_mode"] = getattr(mat, "alphaMode", None)
            slots = {s: getattr(mat, s, None) for s in TEXTURE_SLOTS}
            if slots["baseColorTexture"] is None:
                slots["baseColorTexture"] = getattr(mat, "image", None)
            for slot, img in slots.items():
                if img is None or UV is None:
                    continue
                data, mime, size = _shrink_image(img, max_texture, jpeg_quality)
                material["textures"][slot] = (data, mime)
                tex_report.append({"slot": slot, "from": list(img.size), "to": list(size),
                                   "mime": mime, "bytes": len(data)})
        elif getattr(vis, "kind", None) in ("vertex", "face") and getattr(vis, "defined", False):
            VC = np.asarray(vis.vertex_colors, np.float64)[:, :4]
        P, F2, UV2, VC2, cell = decimate_clustering(V, F, UV, VC, budget)
        if cell:
            cells.append(cell)
        if UV2 is not None:
            UV2 = np.c_[UV2[:, 0], 1.0 - UV2[:, 1]]      # trimesh v-up -> glTF v-down
        prims.append({"P": P, "F": F2, "UV": UV2, "VC": VC2, "material": material})
    write_glb(dest, prims)
    rep = {"file": dest, "bytes_before": os.path.getsize(src), "bytes_after": os.path.getsize(dest),
           "faces_before": total, "faces_after": int(sum(len(p["F"]) for p in prims)),
           "vertices_after": int(sum(len(p["P"]) for p in prims)),
           "max_texture": max_texture, "max_faces": max_faces, "textures": tex_report,
           "decimation": ("vertex clustering, cell %.5f source units" % max(cells)) if cells
                         else "none (already within the face budget)",
           "normals": "dropped"}
    log(f"[reduce] {os.path.basename(src)}: {rep['bytes_before']:,} B, {total:,} faces -> "
        f"{os.path.basename(dest)}: {rep['bytes_after']:,} B, {rep['faces_after']:,} faces; "
        + "; ".join(f"{t['slot']} {t['from'][0]}x{t['from'][1]} -> {t['to'][0]}x{t['to'][1]} "
                    f"{t['mime']} {t['bytes']:,} B" for t in tex_report))
    return rep


def reduced_name(glb_path):
    base = os.path.basename(glb_path)
    stem = base[:-4] if base.lower().endswith(".glb") else os.path.splitext(base)[0]
    return stem + ".reduced.glb"



def import_mesh(input_path, name, kind="prop", tier=None, size=None, size_axis="y",
                fill=None, clusters=6, merge_dist=30.0, map_overrides=None,
                default_material=None, color_table="tint", only_materials=None,
                exclude_materials=None, emit="tint", compact=None, out_dir=None,
                up="y", preview=False, source="local-mesh", prompt=None, image=None,
                meshy_info=None, stem_prefix=True, check_library=True,
                all_materials=False, color_metric=None, keep_islands=False,
                island_fraction=DEFAULT_ISLAND_FRACTION, era=None, note=None,
                size_basis=None, log=print):
    """Run the whole offline import. Returns a result dict (paths, counts, clusters,
    massing). Raises ImportError_ on a refusal."""
    if size is None or size <= 0:
        raise ImportError_("--size (metres; 1 engine cube = 1 m) is required and must be > 0. "
                           "The tool never guesses a scale.")
    tier = TIER_ALIASES.get(tier, tier) or KIND_DEFAULT_TIER[kind]
    if tier not in TIER_RES:
        raise ImportError_(f"unknown tier '{tier}'")
    if kind == "item" and tier != "fine":
        raise ImportError_("--kind item must use --tier fine (items are the fine-voxel class; "
                           "docs/FineVoxelItems.md)")
    fill = fill or KIND_DEFAULT_FILL[kind]
    if compact is None:
        compact = "none" if tier != "micro" else ("cube" if kind == "building" else "sub")
    res = TIER_RES[tier]
    out_dir = out_dir or default_out_dir()
    os.makedirs(out_dir, exist_ok=True)

    stem = sanitize_stem(name)
    if stem_prefix:
        pre = "meshyref_" if kind == "building" else "meshy_"
        if not stem.startswith(pre):
            stem = pre + stem
    if check_library:
        existing = library_stems()
        if stem in existing:
            raise ImportError_(f"stem '{stem}' already exists in the library "
                               f"({existing[stem]}); stems are unique library-wide - pick "
                               f"another --name")

    all_names = load_material_names()
    # buildings: construction materials only, roof clusters matched within the roof
    # family, chroma-weighted distance - unless the caller names a candidate set
    building_set = kind == "building" and not only_materials and not all_materials
    role_tables = None
    if building_set:
        walls, roofs = building_material_sets(log=log)
        if exclude_materials:
            walls = [n for n in walls if n not in exclude_materials]
            roofs = [n for n in roofs if n not in exclude_materials]
        table = load_material_table(color_table=color_table, only=walls + roofs)
        role_tables = {"wall": load_material_table(color_table=color_table, only=walls),
                       "roof": load_material_table(color_table=color_table, only=roofs)}
        candidate_set = "building (construction materials; roof clusters -> roof family)"
    else:
        table = load_material_table(color_table=color_table, only=only_materials,
                                    exclude=exclude_materials)
        candidate_set = ("only: " + ",".join(sorted(only_materials)) if only_materials
                         else "all materials (category material)")
    color_metric = color_metric or ("chroma" if kind == "building" else "rgb")

    parts = load_parts(input_path, up=up)
    n_faces = sum(len(p.faces) for p in parts)
    image = rel_ref(image)
    size_basis = (size_basis or "").strip() or "NOT STATED"
    vox = voxelize(parts, res, size, size_axis, log=log)
    # stray pieces (buildings only): decided on the first pass, then the kept
    # triangles are voxelized again so the box and the scale are the building's
    islands = None
    if kind == "building":
        if keep_islands:
            islands = {"applied": False, "reason": "--keep-islands"}
        else:
            face_keep, islands = find_islands(vox, island_fraction)
            islands["extent_m_with_islands"] = [round(v, 4) for v in vox["extent_m"]]
            if islands["dropped_components"]:
                vox = voxelize(parts, res, size, size_axis, log=log, face_keep=face_keep)
            islands["extent_m_kept"] = [round(v, 4) for v in vox["extent_m"]]
    grid, cl = build_label_grid(vox, clusters, merge_dist)
    if islands and islands["applied"]:
        from scipy import ndimage
        islands["components_after"] = int(ndimage.label(
            grid >= 0, structure=np.ones((3, 3, 3), bool))[1])
    n_surface = int((grid >= 0).sum())
    if n_surface == 0:
        raise ImportError_("voxelization produced no voxels")
    geo = None
    if kind == "building":
        geo = massing_geometry(grid)
        if role_tables:
            assign_roles(grid, cl, geo)
    cl = map_clusters(cl, table, map_overrides or {}, default_material, all_names,
                      metric=color_metric, role_tables=role_tables)

    n_interior = 0
    if fill == "solid":
        grid, n_interior = fill_solid(grid)
    for c in cl:
        c["voxels"] = int((grid == c["id"]).sum())

    lines, counts = emit_lines(grid, cl, tier, emit == "tint", compact)
    dims = [int(d) for d in grid.shape]
    pitch = 1.0 / res
    mats_used = sorted({c["material"] for c in cl if c["voxels"]})
    today = datetime.date.today().isoformat()

    massing = None
    if kind == "building":          # computed on the grid AFTER the island filter
        m = massing_report(grid, res, cl, geo)
        massing = {"_note": m.pop("_note"), "size_m": size, "size_axis": vox["size_axis"],
                   "size_basis": size_basis,
                   "islands_dropped": (f"{islands['dropped_components']} components, "
                                       f"{islands['dropped_voxels']} voxels"
                                       if islands["applied"] else "filter off (--keep-islands)"),
                   **m}

    src_desc = {"meshy": "Meshy AI mesh", "local-mesh": "local mesh"}[source]
    header = [
        "# ==========================================================",
        "# ASSET METADATA",
        f"# name:         {stem}",
        f"# description:  Voxelized from a {src_desc} ({os.path.basename(input_path)}) "
        f"by tools/meshy_import.py",
        f"# category:     {KIND_HEADER_CATEGORY[kind]}",
        f"# materials:    {', '.join(mats_used)}",
        f"# bounds:       {dims[0] * pitch:.3f}W x {dims[1] * pitch:.3f}H x "
        f"{dims[2] * pitch:.3f}D m  ({dims[0]}x{dims[1]}x{dims[2]} cells at 1/{res} m; "
        f"requested {size} m along {vox['size_axis']})",
        f"# size basis:   {size_basis}",
        f"# primitives:   {counts['C']} C + {counts['S']} S + {counts['M']} M + {counts['V']} V"
        f"  ({n_surface + n_interior} voxels: {n_surface} surface + {n_interior} interior, "
        f"fill={fill})",
        f"# source:       {source}"
        + (f"; prompt: {prompt}" if prompt else "") + (f"; image: {image}" if image else ""),
        f"# method:       tools/meshy_import.py --kind {kind} --tier {tier}",
        f"# created:      {today}",
    ]
    if kind == "building":
        header += [
            "# REFERENCE ONLY: a Meshy building is a reference for the structure generator's",
            "# rules. It is never placed in a world as generator output (CLAUDE.md provenance).",
        ]
    header.append("# ==========================================================")
    if tier == "fine":
        header += [f"# grid: {res}", "# category: item"]
    header.append("")

    voxel_path = os.path.join(out_dir, stem + ".voxel")
    with open(voxel_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(header + lines) + "\n")

    files = {"voxel": voxel_path}
    if massing:
        mp = os.path.join(out_dir, stem + ".massing.json")
        with open(mp, "w", encoding="utf-8", newline="\n") as f:
            json.dump(massing, f, indent=2)
        files["massing"] = mp

    preview_text = None
    if preview:
        preview_text = ascii_preview(grid, cl)
        tp = os.path.join(out_dir, stem + ".preview.txt")
        with open(tp, "w", encoding="utf-8", newline="\n") as f:
            f.write(preview_text + "\n")
        files["preview_txt"] = tp
        pp = os.path.join(out_dir, stem + ".preview.png")
        if png_preview(grid, cl, pp, f"{stem}  {tier} 1/{res} m  "
                                     f"{dims[0] * pitch:.2f} x {dims[1] * pitch:.2f} x "
                                     f"{dims[2] * pitch:.2f} m  (front / side / top)"):
            files["preview_png"] = pp
        else:
            log("[meshy_import] PIL not installed - text preview only")

    # lint (the existing gate, unchanged, on this one file)
    sys.path.insert(0, TOOLS_DIR)
    import lint_voxel_detail
    lint_problems = lint_voxel_detail.lint(Path(voxel_path))

    tags = ["meshy" if source == "meshy" else "local-mesh", "generated", kind]
    if kind == "building":
        tags += ["reference", "do-not-place"]
    provenance = {
        "stem": stem,
        "source": source,
        "prompt": prompt,
        "image": image,
        "meshy": meshy_info,
        "input_file": repo_rel(input_path),
        "input_sha256": sha256_file(input_path),
        "input_faces": n_faces,
        "date": today,
        "kind": kind,
        "tier": tier,
        "cells_per_metre": res,
        "era": era,
        "note": note,
        "size_m": size,
        "size_basis": size_basis,
        "size_axis": vox["size_axis"],
        "islands": islands,
        "uniform_scale_applied": vox["scale"],
        "extent_m": [round(d * pitch, 4) for d in dims],
        "extent_cells": dims,
        "fill": fill,
        "compact": compact,
        "emit": emit,
        "color_table": color_table,
        "color_metric": color_metric,
        "candidate_materials": candidate_set,
        "voxels": {"surface": n_surface, "interior": n_interior,
                   "total": n_surface + n_interior},
        "primitives": counts,
        "clusters": [{k: c[k] for k in ("id", "rgb", "tint", "material", "how", "role",
                                        "surface_voxels", "voxels") if k in c} for c in cl],
        "tool": "tools/meshy_import.py",
        "verified_in_engine": False,
        # intent fields asset_index.py preserves across regeneration (its PRESERVED
        # tuple); `--register` seeds the catalog entry with these.
        "catalog_intent": {
            "display_name": stem.replace("_", " ").title(),
            "description": (f"Voxelized from a {src_desc} by tools/meshy_import.py "
                            f"({tier} tier, {size} m along {vox['size_axis']})."
                            + (" REFERENCE ONLY - never placed as generator output."
                               if kind == "building" else "")),
            "tags": tags,
            "method": f"tools/meshy_import.py (source: {source}"
                      + (f", {meshy_info['mode']}" if meshy_info else "") + ")",
            "model": (meshy_info or {}).get("ai_model") or
                     ("meshy" if source == "meshy" else "local-mesh"),
            "created": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "version": 1,
            **({"prompt": prompt or f"image: {image}"} if (prompt or image) else {}),
        },
    }
    prov_path = os.path.join(out_dir, stem + ".provenance.json")
    with open(prov_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(provenance, f, indent=2)
    files["provenance"] = prov_path

    return {"stem": stem, "files": files, "dims_cells": dims, "res": res, "pitch": pitch,
            "counts": counts, "voxels": provenance["voxels"], "clusters": cl,
            "massing": massing, "lint_problems": lint_problems, "preview_text": preview_text,
            "provenance": provenance, "extent_m_mesh": vox["extent_m"], "grid": grid}



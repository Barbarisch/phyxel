def _bands(values, threshold, min_len):
    """[start, end) index runs where values >= threshold, at least min_len long."""
    out, start = [], None
    for i, v in enumerate(list(values) + [threshold - 1]):
        if v >= threshold and start is None:
            start = i
        elif v < threshold and start is not None:
            if i - start >= min_len:
                out.append((start, i))
            start = None
    return out


def massing_geometry(grid):
    """Roof geometry in CELLS, from occupancy only (no colours). Used by the
    massing report and by the roof/wall split of the building material mapping."""
    occ = grid >= 0
    nx, ny, nz = occ.shape
    col = occ.any(axis=1)                                             # (x,z)
    top = np.where(col, ny - np.argmax(occ[:, ::-1, :], axis=1), 0)   # column top, cells
    top_cells = int(top.max())
    # silhouette extent per layer: occupied positions along x / along z
    ext = {"x": occ.any(axis=2).sum(axis=0).astype(np.float64),
           "z": occ.any(axis=0).sum(axis=1).astype(np.float64)}
    upper = slice(int(0.7 * top_cells), top_cells)
    shrink = {a: float((ext[a][upper] / max(1.0, ext[a].max())).mean()) for a in "xz"}
    pitch_axis = min("xz", key=lambda a: shrink[a])
    if shrink[pitch_axis] > 0.9:                    # neither silhouette narrows: no pitch
        pitch_axis = None
    ridge_axis = None if pitch_axis is None else ("z" if pitch_axis == "x" else "x")
    ridge_cells = top_cells
    if ridge_axis:
        long_enough = np.nonzero(ext[ridge_axis] >= 0.5 * ext[ridge_axis].max())[0]
        ridge_cells = int(long_enough.max()) + 1
    eaves_cells, span_cells = ridge_cells, 0
    if pitch_axis:
        w = ext[pitch_axis]
        y0 = int(0.3 * ridge_cells)
        wmax = float(w[y0:ridge_cells].max())
        widest = np.nonzero(w[y0:ridge_cells] >= 0.97 * wmax)[0]
        eaves_cells = y0 + int(widest.max()) + 1
        span_cells = int(w[eaves_cells - 1])
    return {"top": top, "col": col, "top_cells": top_cells, "ridge_cells": ridge_cells,
            "eaves_cells": eaves_cells, "span_cells": span_cells,
            "pitch_axis": pitch_axis, "ridge_axis": ridge_axis, "shrink": shrink}


def assign_roles(grid, clusters, geo):
    """Tag each cluster 'roof' or 'wall' from WHERE it sits: roof = at least half of
    its voxels lie above the eaves AND it shows on at least 10 % of the plan view
    above the eaves. Detector thresholds, not standards."""
    ev = geo["eaves_cells"]
    top_lab = view_labels(grid)["top"].T                      # (x,z) label seen from above
    roof_cols = geo["col"] & (geo["top"] > ev)
    n_roof_cols = int(roof_cols.sum())
    for c in clusters:
        m = grid == c["id"]
        n = int(m.sum())
        above = int(m[:, max(0, ev - 1):, :].sum())
        share = (float(((top_lab == c["id"]) & roof_cols).sum()) / n_roof_cols
                 if n_roof_cols else 0.0)
        c["above_eaves_fraction"] = round(above / n, 3) if n else 0.0
        c["plan_view_roof_share"] = round(share, 3)
        c["role"] = "roof" if (n and above / n >= 0.5 and share >= 0.10) else "wall"
    return clusters


def _facade_rows(lab, res, pitch):
    """Opening rows on one facade label image lab[u, y] (-1 = empty, already cut at
    the eaves). Returns (rows [[y0_m, y1_m]], wall cluster id, frame cluster ids)."""
    from scipy import ndimage
    present = lab >= 0
    if not present.any():
        return [], None, []
    width = int(present.any(axis=1).sum())
    wall = int(np.bincount(lab[present]).argmax())
    eight = np.ones((3, 3), bool)
    along_u = np.array([[0, 1, 0], [0, 1, 0], [0, 1, 0]], bool)
    frames, opening = [], np.zeros(lab.shape, bool)
    for cid in np.unique(lab[present]):
        if cid == wall:
            continue
        m = lab == cid
        framed = False
        # (a) a horizontal run longer than a quarter of the facade is a rail, a band
        #     course, the plinth or the roof's lower edge - not an opening
        runs, n = ndimage.label(m, structure=along_u)
        for i, sl in enumerate(ndimage.find_objects(runs), start=1):
            if sl[0].stop - sl[0].start > 0.25 * width:
                m[sl][runs[sl] == i] = False
                framed = True
        # (b) what is still one connected piece wider than half the facade (a frame
        #     network), or at least three times taller than wide (a post), goes too
        comp, n = ndimage.label(m, structure=eight)
        for i, sl in enumerate(ndimage.find_objects(comp), start=1):
            w_, h_ = sl[0].stop - sl[0].start, sl[1].stop - sl[1].start
            if w_ > 0.5 * width or h_ >= 3 * w_:
                m[sl][comp[sl] == i] = False
                framed = framed or w_ > 0.5 * width
        if framed:
            frames.append(int(cid))
        opening |= m
    k = max(2, int(round(0.3 * res)))                 # drop specks narrower than ~0.3 m
    opening = ndimage.binary_opening(opening, structure=np.ones((k, k), bool))
    comp, n = ndimage.label(opening, structure=eight)
    for i in range(1, n + 1):                         # a blob wider than half the facade
        us = np.nonzero((comp == i).any(axis=1))[0]   # is not a window
        if us.max() - us.min() + 1 > 0.5 * width:
            opening[comp == i] = False
    count = opening.sum(axis=0)
    if count.max() == 0:
        return [], wall, frames
    thr = max(0.35 * float(count.max()), float(k))
    hit = (count >= thr).astype(np.uint8)
    gap = max(1, int(round(0.5 * res)))               # a dip under ~0.5 m (a transom, a
    hit = ndimage.binary_closing(np.r_[np.zeros(gap, np.uint8), hit, np.zeros(gap, np.uint8)],
                                 structure=np.ones(gap + 1, bool))[gap:-gap]   # sill) is not
    rows = [[round(a * pitch, 3), round(b * pitch, 3)]                         # a new row
            for a, b in _bands(hit.astype(int), 1, max(2, int(math.ceil(0.75 * res))))]
    return rows, wall, frames


def massing_report(grid, res, clusters, geo=None):
    """Measure a building's massing from its voxel grid. Heights are above the
    model's lowest voxel. Nothing here comes from a real-world source."""
    from scipy import ndimage
    pitch = 1.0 / res
    occ = grid >= 0
    nx, ny, nz = occ.shape
    geo = geo or massing_geometry(grid)
    col, top = geo["col"], geo["top"]
    eaves_cells, ridge_cells = geo["eaves_cells"], geo["ridge_cells"]
    axis_name = geo["pitch_axis"]

    # the previous eaves rule, kept as a second reading
    solid = ndimage.binary_fill_holes(occ)
    area = solid.sum(axis=(0, 2)).astype(np.float64)
    eaves95_cells = int(np.nonzero(area >= 0.95 * area.max())[0].max()) + 1

    pitch_rr = pitch_grad = None
    roof = col & (top > eaves_cells) & (top <= ridge_cells)
    if axis_name and roof.any() and ridge_cells > eaves_cells:
        h = top.astype(np.float64)
        if axis_name == "x":
            steps = np.abs(np.diff(h, axis=0))[roof[1:, :] & roof[:-1, :]]
        else:
            steps = np.abs(np.diff(h, axis=1))[roof[:, 1:] & roof[:, :-1]]
        rise = (ridge_cells - eaves_cells) * pitch
        run = geo["span_cells"] * pitch / 2.0
        if run > 0:
            pitch_rr = math.degrees(math.atan2(rise, run))
        if steps.size:
            pitch_grad = math.degrees(math.atan(float(steps.mean())))

    # storeys: rows of openings on the two LONG facades (the faces along the
    # longer plan dimension), read below the eaves
    long_axis = "x" if nx >= nz else "z"
    g = grid[:, :eaves_cells, :]

    def first_hit(axis, from_plus):
        o = g >= 0
        gg, oo = (np.flip(g, axis=axis), np.flip(o, axis=axis)) if from_plus else (g, o)
        i = np.argmax(oo, axis=axis)
        lab = np.take_along_axis(gg, np.expand_dims(i, axis), axis=axis).squeeze(axis)
        return np.where(o.any(axis=axis), lab, -1)

    facades = {}
    view_axis = 2 if long_axis == "x" else 0          # look along the SHORT dimension
    for name, plus in (("plus", True), ("minus", False)):
        lab = first_hit(view_axis, plus)              # (x,y) or (y,z)
        if view_axis == 0:
            lab = lab.T                               # -> (z,y)
        rows, wall, frames = _facade_rows(lab, res, pitch)
        side = ("+" if plus else "-") + ("z" if long_axis == "x" else "x")
        facades[side] = {"opening_rows_m": rows, "wall_cluster": wall,
                         "frame_clusters": frames}
    best = max(facades, key=lambda s: len(facades[s]["opening_rows_m"]))
    rows = facades[best]["opening_rows_m"]
    storey_guess = len(rows) if rows else None

    return {
        "_note": "EVERY NUMBER HERE IS MEASURED FROM THE MODEL'S VOXELS at the --size the "
                 "importer was given. None of it is a real-world source; a dimension typed "
                 "into engine data still needs its own citation (grounding-auditor).",
        "voxel_pitch_m": round(pitch, 5),
        "footprint_w_x_m": round(nx * pitch, 3),
        "footprint_d_z_m": round(nz * pitch, 3),
        "footprint_area_m2": round(float(col.sum()) * pitch * pitch, 3),
        "footprint_fill_ratio": round(float(col.sum()) / (nx * nz), 3),
        "eaves_height_m": round(eaves_cells * pitch, 3),
        "eaves_method": "top of the highest layer (above 30% of the ridge height) whose "
                        "silhouette extent across the roof-pitch axis is >= 97% of the "
                        "widest such layer: the height above which the building only "
                        "narrows. With an overhanging roof this is the roof's lower edge, "
                        "not the top of the wall. No pitch axis -> equals the ridge.",
        "eaves_height_95pct_layer_m": round(eaves95_cells * pitch, 3),
        "eaves_95pct_method": "the earlier rule, kept for comparison: top of the highest "
                              "layer whose solid cross-section is >= 95% of the largest",
        "ridge_height_m": round(ridge_cells * pitch, 3),
        "ridge_method": "top of the highest layer whose extent along the ridge axis is >= "
                        "50% of the building's (so a chimney or finial is not the ridge)",
        "top_height_m": round(geo["top_cells"] * pitch, 3),
        "roof_span_across_pitch_axis_m": round(geo["span_cells"] * pitch, 3),
        "roof_pitch_deg_rise_over_run": None if pitch_rr is None else round(pitch_rr, 1),
        "roof_pitch_deg_mean_gradient": None if pitch_grad is None else round(pitch_grad, 1),
        "roof_pitch_axis": axis_name,
        "roof_pitch_method": "axis = the horizontal axis along which the silhouette narrows "
                             "in the top 30% of the height (null if neither does); rise/run "
                             "= (ridge - eaves) / (half the roof span at the eaves), assumes "
                             "a symmetric roof; mean gradient = atan of the mean column-top "
                             "step along that axis between eaves and ridge",
        "long_facades": facades,
        "opening_rows_m": rows,
        "opening_rows_facade": best if rows else None,
        "storey_count_guess": storey_guess,
        "storey_method": "on each of the two long facades (first surface seen along the "
                         "shorter plan axis, below the eaves): drop the dominant wall "
                         "cluster; per remaining cluster drop horizontal runs longer than a "
                         "quarter of the facade (rail, band course, plinth, roof edge), "
                         "connected pieces wider than half the facade (frame network) and "
                         "pieces 3x taller than wide (posts); what is left, after removing "
                         "specks under ~0.3 m, is counted per height; a row is a band >= "
                         "0.75 m where that count is >= 35% of its peak, dips under ~0.5 m "
                         "bridged. Guess = rows on the facade with "
                         "more rows; null = none found. A guess, labelled as one.",
        "wall_cluster": facades[best]["wall_cluster"],
    }



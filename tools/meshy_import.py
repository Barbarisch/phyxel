def sanitize_stem(s):
    s = re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")
    if not s:
        raise ImportError_("empty template name")
    return s


def library_stems(templates_dir=TEMPLATES):
    stems = {}
    for dp, _dn, fns in os.walk(templates_dir):
        for fn in fns:
            if fn.endswith(".voxel"):
                stems[fn[:-6]] = os.path.relpath(os.path.join(dp, fn), templates_dir)
    return stems


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()



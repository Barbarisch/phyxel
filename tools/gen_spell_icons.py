# The action-bar rows that are not spells.
EXTRA = {"attack": ("swords", "steel"), "end_turn": ("hourglass", "bronze")}


def parse_glyph(art):
    rows = [r for r in art.strip("\n").split("\n")]
    out = []
    for r in rows:
        if len(r) > CELL:
            raise ValueError("glyph row is %d wide, max %d: %r" % (len(r), CELL, r))
        out.append(r.ljust(CELL, "."))
    if len(out) > CELL:
        raise ValueError("glyph is %d rows, max %d" % (len(out), CELL))
    # centre vertically so a short glyph is not top-heavy in the slot
    pad = (CELL - len(out)) // 2
    return ["." * CELL] * pad + out + ["." * CELL] * (CELL - len(out) - pad)


def render_icon(glyph_name, palette):
    main, light, accent, badge = PAL[palette]
    shadow = tuple(int(c * 0.45) for c in main)
    colors = {"#": main, "+": light, "*": accent, "o": shadow}

    img = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
    px = img.load()
    # Badge plate: a rounded square, so the icon reads as a slot rather than a floating shape.
    for y in range(CELL):
        for x in range(CELL):
            corner = (x in (0, CELL - 1)) and (y in (0, CELL - 1))
            if not corner:
                px[x, y] = badge + (232,)
    # A one-pixel rim in the palette's main colour keys the slot to the spell.
    rim = tuple(int(c * 0.75) for c in main) + (255,)
    for i in range(1, CELL - 1):
        px[i, 0] = rim
        px[i, CELL - 1] = rim
        px[0, i] = rim
        px[CELL - 1, i] = rim

    for y, row in enumerate(parse_glyph(GLYPH[glyph_name])):
        for x, ch in enumerate(row):
            if ch in colors:
                px[x, y] = colors[ch] + (255,)
    return img.resize((SIZE, SIZE), Image.NEAREST)


def load_spells():
    spells = []
    for f in sorted(glob.glob(os.path.join(SPELL_DIR, "*.json"))):
        d = json.load(open(f, encoding="utf-8"))
        spells.extend(d if isinstance(d, list) else d.get("spells", []))
    return spells


def palette_for(spell):
    dmg = (spell.get("damageType") or "").lower()
    if dmg in PAL:
        return dmg
    if spell.get("healDice") or spell.get("healBase"):
        return "heal"
    return (spell.get("school") or "evocation").lower()


def glyph_for(spell):
    sid = spell["id"]
    if sid in SPELL_GLYPH:
        return SPELL_GLYPH[sid]
    return SCHOOL_GLYPH.get((spell.get("school") or "").lower(), "burst")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sheet", action="store_true", help="also write a contact sheet")
    ap.add_argument("--check", action="store_true",
                    help="do not write; fail if any spell's icon file is missing")
    args = ap.parse_args()

    spells = load_spells()
    if not spells:
        print("no spells found under %s" % SPELL_DIR, file=sys.stderr)
        return 1

    if args.check:
        no_glyph = [s["id"] for s in spells if s["id"] not in SPELL_GLYPH]
        absent = [s["id"] for s in spells
                  if not os.path.exists(os.path.join(OUT_DIR, s["id"] + ".png"))]
        absent += [n for n in EXTRA if not os.path.exists(os.path.join(OUT_DIR, n + ".png"))]
        for sid in no_glyph:
            print("note: spell '%s' has no glyph of its own (uses its school's)" % sid)
        for sid in absent:
            print("MISSING ICON FILE: %s.png - run tools/gen_spell_icons.py" % sid)
        print("%d spells, %d with their own glyph, %d icon files missing"
              % (len(spells), len(spells) - len(no_glyph), len(absent)))
        return 1 if absent else 0

    os.makedirs(OUT_DIR, exist_ok=True)
    written = []
    for s in spells:
        render_icon(glyph_for(s), palette_for(s)).save(os.path.join(OUT_DIR, s["id"] + ".png"))
        written.append((s["id"], s["name"], glyph_for(s), palette_for(s)))
    for name, (g, p) in EXTRA.items():
        render_icon(g, p).save(os.path.join(OUT_DIR, name + ".png"))
        written.append((name, name, g, p))
    # Per-school fallbacks, so a spell added to the JSON still gets a sensible icon
    # even before this script is re-run.
    for school, g in SCHOOL_GLYPH.items():
        render_icon(g, school).save(os.path.join(OUT_DIR, "school_" + school + ".png"))

    for sid, nm, g, p in written:
        print("  %-20s %-22s %-14s %s" % (sid, nm, g, p))
    print("%d icons -> %s" % (len(written) + len(SCHOOL_GLYPH), OUT_DIR))

    if args.sheet:
        cols = 8
        rows = (len(written) + cols - 1) // cols
        pad, label_h = 8, 14
        sheet = Image.new("RGB", (cols * (SIZE + pad) + pad,
                                  rows * (SIZE + pad + label_h) + pad), (24, 24, 28))
        d = ImageDraw.Draw(sheet)
        for i, (sid, nm, g, p) in enumerate(written):
            cx = pad + (i % cols) * (SIZE + pad)
            cy = pad + (i // cols) * (SIZE + pad + label_h)
            ic = Image.open(os.path.join(OUT_DIR, sid + ".png"))
            sheet.paste(ic, (cx, cy), ic)
            d.text((cx, cy + SIZE + 2), sid[:16], fill=(200, 200, 210))
        out = os.path.join(REPO, "docs", "evidence", "ravenmere", "spell_icon_sheet.png")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        sheet.save(out)
        print("contact sheet -> %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())

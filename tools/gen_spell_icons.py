#!/usr/bin/env python3
"""gen_spell_icons.py - one pixel-art icon per spell, plus the non-spell action-bar actions.

WHY GENERATED. The spell list is data (resources/spells/*.json) and it grows; a hand-painted
icon set goes stale the moment a spell is added. This reads the same JSON the engine loads,
so every spell it knows about gets an icon, and an unknown spell still resolves to its
school's fallback instead of a blank slot.

SIZE. Drawn on a 16x16 grid, scaled 4x nearest-neighbour to 64x64 px - the chunky pixel look
that matches the voxel aesthetic, and the size the source art is authored at. The HUD draws
them at 44 px inside a 52 px action-bar slot, which follows the shipped hotbar's own
proportions (a 46 px icon inside a 62 px slot, resources/ui/default_hud.json).

COLOUR is data-driven, not decoration: damage type first (a Fire spell is orange, a Necrotic
one sickly green), then healing, then school. Two spells never share both a glyph and a
palette.

  python tools/gen_spell_icons.py            # write resources/ui/icons/spells/*.png
  python tools/gen_spell_icons.py --sheet    # also write a contact sheet to review the set
  python tools/gen_spell_icons.py --check    # fail if any spell has no icon file
"""

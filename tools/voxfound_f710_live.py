"""F7.10 live (docs/evidence/voxfound_f7_prediction.txt Q1-Q4): spawn_template on the switched world. VoxFoundGate (8120).
Region: the gate box, flora_window open, switched with load_saved false. Templates: barrel (resources/templates_g8
furniture, generated by tools/regen_furniture.py --grid 8 -- FC step 4); placed through POST /api/world/template.
Modes: control / red (template_stub) / green. Every artifact: WorldGenerator Perlin s7 + flora (the region) + the
generated 1/8 m templates."""
import json, math, os, sys, time, urllib.request

API = "http://127.0.0.1:8120"
P = "/api/debug/voxfound_preview"
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
EVID = os.path.join(REPO, "docs", "evidence")
REGION = {"type": "Perlin", "seed": 7, "flora": True, "editable": True, "hide_world": False, "flora_window": "open",
          "region": {"from": [254, 0, 2], "to": [257, 1, 5]}}


def call(m, p, b=None):
    r = urllib.request.Request(API + p, data=json.dumps(b).encode() if b is not None else None, method=m,
                               headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(r, timeout=3600) as resp:
            return json.loads(resp.read().decode())
    except urllib.error.HTTPError as e:
        return {"http_status": e.code, "body": e.read().decode()[:300]}


def hashes():
    return {",".join(map(str, c["chunk"])): c["hash_by_name"] for c in call("POST", P, {"store_hash": True})["chunks"]}


def spawn(x, y, z, **kw):
    b = {"name": "barrel", "position": {"x": x, "y": y, "z": z}}
    b.update(kw)
    return call("POST", "/api/world/template", b)


def solid_sum(lo_v, hi_v):   # GET /api/world/voxel over the cubes covering a voxel box
    n = 0
    for cx in range(lo_v[0] // 8, hi_v[0] // 8 + 1):
        for cy in range(lo_v[1] // 8, hi_v[1] // 8 + 1):
            for cz in range(lo_v[2] // 8, hi_v[2] // 8 + 1):
                n += (call("GET", f"/api/world/voxel?x={cx}&y={cy}&z={cz}").get("voxfound") or {}).get("solid_voxels", 0)
    return n


def main():
    mode = sys.argv[1]
    out = {"mode": mode}
    call("POST", P, REGION)
    if mode == "red":
        out["stub"] = call("POST", P, {"template_stub": True})
    call("POST", P, {"world_switch": True, "load_saved": False})
    h0 = hashes()
    r1 = spawn(8132.0, 30.0, 68.0, snap=False)
    out["Q1_spawn"] = {k: r1.get(k) for k in ("success", "world", "voxels_changed", "template_cells", "verify_bad",
                                              "lo", "hi", "undo", "error")}
    h1 = hashes()
    out["region_chunks_changed"] = [k for k in h0 if h0[k] != h1[k]]
    if mode == "green":
        out["Q1_get_sum"] = solid_sum(r1["lo"], r1["hi"])
        r2 = spawn(8140.0, 30.0, 80.0, snap=False, rotation=1)
        out["Q2"] = {k: r2.get(k) for k in ("voxels_changed", "lo", "hi")}
        ext1 = [r1["hi"][i] - r1["lo"][i] for i in range(3)]
        ext2 = [r2["hi"][i] - r2["lo"][i] for i in range(3)]
        out["Q2_extents"] = {"rot0": ext1, "rot1": ext2, "xz_swapped": ext1[0] == ext2[2] and ext1[2] == ext2[0]}
        r3 = spawn(8150.0, 34.0, 90.0)   # snap (default)
        out["Q3"] = {k: r3.get(k) for k in ("voxels_changed", "lo", "hi", "snap_ground_top", "error")}
        n = 0
        while True:
            u = call("POST", "/api/undo", {})
            if u.get("world") != "voxfound":
                break
            n += 1
        out["Q4_undos"] = n
        out["Q4_back_to_start"] = sum(hashes()[k] == h0[k] for k in h0)
    call("POST", P, {"world_switch": False})
    out["today_after"] = call("GET", "/api/world/voxel?x=8132&y=30&z=68")
    if mode == "red":
        call("POST", P, {"template_stub": False})
    print(json.dumps(out)[:4000])
    with open(os.path.join(EVID, "voxfound_f710_live.jsonl"), "a") as f:
        f.write(json.dumps(out) + "\n")


if __name__ == "__main__":
    main()

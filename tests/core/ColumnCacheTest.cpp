#include <gtest/gtest.h>

#include <algorithm>
#include <cmath>
#include <cstdio>
#include <memory>
#include <vector>

#include "core/Chunk.h"
#include "core/WorldGenerator.h"
#include "core/WorldRecipe.h"

using namespace Phyxel;

// ============================================================================
// ColumnCacheTest: the streaming workers' column-cache behaviour, reproduced without the engine.
// MEASURED in the engine (docs/evidence/worldforge_v2/m1e_cpu_profile_summary.json, 2026-10-20):
// each generated chunk sampled 32.06 FRESH 32x32 column blocks (column-cache misses), cpu/wall
// 0.96, meso bakes 0 — the whole 100 ms/chunk of column time was cache thrash, not slow columns
// (the bench measures 1.9 us per column). Cause: the water-span batch pads a chunk by
// kWaterExtentSteps (256) on every side = a 19x19-block neighbourhood per chunk, the column cache is a
// 512-entry FIFO, and under the camera-priority wanted order split across three workers the FIFO
// evicts the hot centre blocks first (WorldGenerator.cpp's own comment predicted the failure).
//
// Rig: a worker's view of streaming — the 17x17 chunk columns around the gate pose, 3 vertical
// bands, sorted by distance from the camera (the manager's priority), every third chunk to THIS
// worker. Fresh blocks per generated chunk must stay near 1 (its own column, first time) plus the
// padded frontier; the first version of the cache measured ~32.
// ============================================================================
namespace {
WorldRecipe baselineRecipe() {
    WorldRecipe r;
    r.version = 2;
    r.type = "Perlin";
    r.seed = 20260816u;
    r.worldforge.enabled = true;
    r.worldforge.siteCount = 8;
    r.worldforge.regionRadius = 2048;
    r.worldforge.minSpacing = 400;
    r.creekCarve = true;
    return r;
}
}  // namespace

TEST(ColumnCacheTest, AWorkerStreamingTheGatePoseSamplesFewFreshBlocksPerChunk) {
    WorldGenerator base(WorldGenerator::GenerationType::Perlin, 20260816u);
    base.applyRecipe(baselineRecipe());
    WorldGenerator worker = base;   // the worker's private copy, its own column cache
    const int ccx = 300 / 32, ccz = -1400 / 32;
    const int bandY = 69 / 32;      // the gate pose's surface band
    std::vector<glm::ivec3> wanted;
    for (int dz = -8; dz <= 8; ++dz)
        for (int dx = -8; dx <= 8; ++dx)
            for (int dy = -1; dy <= 1; ++dy) wanted.emplace_back(ccx + dx, bandY + dy, ccz + dz);
    std::sort(wanted.begin(), wanted.end(), [&](const glm::ivec3& a, const glm::ivec3& b) {
        const float da = std::hypot(float(a.x - ccx), float(a.z - ccz)), db = std::hypot(float(b.x - ccx), float(b.z - ccz));
        return da < db;
    });
    const uint64_t blocks0 = WorldGenerator::columnBlocksThisThread();
    int generated = 0;
    for (size_t i = 0; i < wanted.size(); i += 3) {   // worker 0 of 3
        auto chunk = std::make_unique<Chunk>(wanted[i] * 32);
        chunk->initializeForLoading();
        worker.generateChunk(*chunk, wanted[i]);
        ++generated;
    }
    const double perChunk = static_cast<double>(WorldGenerator::columnBlocksThisThread() - blocks0) / generated;
    // The floor is ANALYTIC, not fitted: every block this worker touches is sampled exactly once by a
    // working cache — its own 17x17 columns plus the water-span padding (kWaterExtentSteps = 256 u =
    // 8 blocks each side -> 33x33 padded area) — divided by the chunks it generates. With the FIFO
    // the measured figure was 32 in the engine; a cache that keeps the padded neighbourhood resident
    // can only pay the floor. 10 % slack for the band-interleaved order.
    const double floorBlocks = (17.0 * 17.0 + 33.0 * 33.0) / generated;
    std::printf("[ column cache ] %d chunks generated by one of three workers: %.2f fresh column blocks per chunk (analytic floor %.2f)\n",
                generated, perChunk, floorBlocks);
    EXPECT_LE(perChunk, floorBlocks * 1.1) << perChunk << " fresh blocks per chunk vs the floor " << floorBlocks
                                           << ": the column cache is thrashing (engine measured 32.06 with the FIFO)";
}

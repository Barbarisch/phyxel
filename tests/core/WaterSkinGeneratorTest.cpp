// WaterCore §51.4 S3 step 2 - the far skin's GENERATOR source (docs/WaterCore.md 51.4): a chunk column never loaded is summarized
// from the generator's water (generatedWaterRuns), so a far lake does not depend on which chunks happened to load. It must equal what
// the generated chunks store, or the skin would change where a chunk loads (a chunk made visible).
// Predictions, written before the first run:
//   - TheGeneratorSummaryEqualsTheGeneratedChunks (equality (ii)): the 3 x 3 chunk columns round a wet column of the Mountains seed-7
//     bake - every 4 m cell of the summary from generatedWaterRuns equals the summary of the spans generateChunk stored in the column
//     stack's chunks (generated by a second generator). Control: one wet column dropped from the chunks' runs (an edit) - cells differ.
//   - DiagGeneratorSourceCost: what one chunk column costs (the flood + margin sampling), printed - it decides whether the source
//     can run on the main thread under the summary budget or needs a worker.

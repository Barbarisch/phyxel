// Tavern signage — the sign is a fine-voxel ITEM, not a blank furniture board.
//
// The generated tavern used to hang `hanging_sign` (furniture/hanging_sign.voxel):
// a bracket + a BLANK painted board. It cannot say anything, so a generated
// tavern was nameless. resources/templates/items/sign_prancing_pony.voxel is a
// fine-grid item carrying a real projected sign image — that is what a tavern
// should hang.
//
// Two things are pinned here:
//  1. The sign asset is DATA on the typology (room_program.json "sign_item"),
//     not a name hard-coded in the forge. A business typology without one falls
//     back to the blank board and records an asset request — it never invents.
//  2. The MOUNT is chosen by fit against the grounded projecting-sign code
//     (>= 8 ft clearance, <= 48 in projection, above the door head). A board too
//     wide to hang on a bracket within that cap mounts FLUSH to the facade
//     instead of being silently skipped — repair-then-refuse, same as every
//     other forge gate.

#include <gtest/gtest.h>

#include <filesystem>

#include "core/ItemRegistry.h"
#include "core/RoomProgram.h"
#include "core/StructureForge.h"

namespace fs = std::filesystem;
using namespace Phyxel;
using namespace Phyxel::Core;

namespace {

bool loadCanon(RoomProgramRegistry& reg) {
    for (const char* p : {"resources/room_program.json", "../resources/room_program.json",
                          "../../resources/room_program.json",
                          "../../../resources/room_program.json"})
        if (reg.loadFromFile(p)) return true;
    return false;
}

// The Prancing Pony board as generated by tools/gen_items.py: 54 x 40 x 1 cells
// on a 27-cell grid = 2.000 x 1.481 x 0.037 u.
constexpr float kPonyW = 54.0f / 27.0f;
constexpr float kPonyH = 40.0f / 27.0f;
constexpr float kPonyT = 1.0f / 27.0f;

}  // namespace

// ---------------------------------------------------------------------------
// 1. The asset is data on the typology.
// ---------------------------------------------------------------------------

TEST(SignMount, TavernDeclaresItsSignAsset) {
    RoomProgramRegistry reg;
    ASSERT_TRUE(loadCanon(reg));
    const RoomProgram* tavern = reg.get("tavern");
    ASSERT_NE(tavern, nullptr);
    EXPECT_EQ(tavern->signItem, "prop_sign_prancing_pony")
        << "the tavern must name its sign asset in room_program.json — the forge "
           "must not hard-code which sign a typology hangs";
}

TEST(SignMount, TheDeclaredSignIsARealHoldableItem) {
    RoomProgramRegistry reg;
    ASSERT_TRUE(loadCanon(reg));
    const RoomProgram* tavern = reg.get("tavern");
    ASSERT_NE(tavern, nullptr);
    ASSERT_FALSE(tavern->signItem.empty());

    ItemRegistry::instance().loadFromFile("resources/items.json");
    const auto* def = ItemRegistry::instance().getItem(tavern->signItem);
    ASSERT_NE(def, nullptr) << tavern->signItem << " is not a registered item";
    EXPECT_TRUE(def->holdable) << "spawnProp refuses non-holdable items";
    ASSERT_FALSE(def->templateFile.empty());
    EXPECT_TRUE(fs::exists("resources/templates/" + def->templateFile))
        << def->templateFile << " missing on disk";
}

// Every declared sign_item must resolve to a REAL registered, holdable item with a
// template on disk — never a borrowed or invented name (the substitution the pipeline
// exists to prevent). Since 2026-08-27 all five trades own authored default boards
// (gen_trade_signs.py); residential typologies still declare nothing.
TEST(SignMount, EveryDeclaredSignAssetResolvesAndHomesStayBlank) {
    RoomProgramRegistry reg;
    ASSERT_TRUE(loadCanon(reg));
    ItemRegistry::instance().loadFromFile("resources/items.json");
    for (const char* name : {"blacksmith", "bakery", "apothecary", "butcher",
                             "general_store"}) {
        const RoomProgram* p = reg.get(name);
        if (!p) continue;
        ASSERT_FALSE(p->signItem.empty())
            << name << " lost its authored default trade sign";
        const auto* def = ItemRegistry::instance().getItem(p->signItem);
        ASSERT_NE(def, nullptr) << name << " declares unregistered sign '" << p->signItem << "'";
        EXPECT_TRUE(def->holdable) << "spawnProp refuses non-holdable items";
        ASSERT_FALSE(def->templateFile.empty());
        EXPECT_TRUE(fs::exists("resources/templates/" + def->templateFile))
            << def->templateFile << " missing on disk";
    }
    for (const char* name : {"croft", "longhouse", "hall_house", "manor_hall"}) {
        const RoomProgram* p = reg.get(name);
        if (!p) continue;
        EXPECT_TRUE(p->signItem.empty()) << name << " is not a trade; no sign";
    }
}


// The corpus run + matrix report. Asserts the harness has TEETH (a stairless multi-story is
// flagged unreachable) and that the canonical exemplar passes; everything else is reported so
// the real pass-rate is visible (the sign-off number).
TEST(BuildingHarness, Corpus) {
    const StyleProfile style = harnessStyle();
    std::vector<Spec> corpus = makeCorpus();

    std::cout << "\n=== BUILDING VALIDATION HARNESS ===\n";
    std::cout << "case                              build  floors  reach  rooms  OVERALL\n";
    int passed = 0;
    CaseResult badStairs, badRooms, exemplar, twoRoomOk, genStripped, genOk, autofillCase;
    for (const auto& c : corpus) {
        CaseResult r = runCase(c.name, c.p, style);
        auto yn = [](bool b) { return b ? " ok " : "FAIL"; };
        const std::string roomsCol = r.build ? (r.roomsTested ? yn(r.rooms) : "n/a ") : "----";
        std::cout << "  " << c.name;
        for (int i = (int)c.name.size(); i < 32; ++i) std::cout << ' ';
        std::cout << "  " << yn(r.build) << "   " << yn(r.floors) << "   " << yn(r.reach)
                  << "   " << roomsCol << "   " << (r.pass() ? "PASS" : "----") << "\n";
        if (r.pass()) ++passed;
        if (c.name == "BAD: 3-story NO stairs") badStairs = r;
        if (c.name == "BAD: 2-room sealed kitchen") badRooms = r;
        if (c.name == "3-story switchback (exemplar)") exemplar = r;
        if (c.name == "2-room connected") twoRoomOk = r;
        if (c.name == "BAD: gen doors stripped") genStripped = r;
        if (c.name == "gen 9x11 rooms=6 seed4") genOk = r;
        if (c.name == "autofill 8x10 (core seam)") autofillCase = r;
    }
    std::cout << "--- " << passed << " / " << corpus.size() << " cases pass ---\n\n";

    // Teeth: a stairless multi-story, a sealed room, AND a generated layout with its interior doors
    // stripped must all be flagged unreachable.
    EXPECT_FALSE(badStairs.reach)   << "no teeth: a stairless 3-story read as reachable";
    EXPECT_FALSE(badRooms.rooms)    << "no teeth: a sealed kitchen read as reachable";
    EXPECT_FALSE(genStripped.rooms) << "no teeth: a door-stripped generated layout read as navigable";
    // Regression guards: exemplar, a doored two-room cottage, and a GENERATED layout fully pass.
    EXPECT_TRUE(exemplar.pass())    << "the 3-story switchback exemplar regressed";
    EXPECT_TRUE(twoRoomOk.pass())   << "a connected two-room cottage is not fully navigable";
    EXPECT_TRUE(genOk.pass())       << "an auto-generated room layout is not fully navigable";
    // The autofill core seam must produce a navigable multi-room building (rooms check applicable).
    EXPECT_TRUE(autofillCase.pass())     << "autofillRoomLayout produced a non-navigable building";
    EXPECT_TRUE(autofillCase.roomsTested) << "autofill produced no multi-room story (rooms was n/a)";
}


StyleProfile harnessStyle() {
    StyleProfileRegistry reg;
    reg.loadFromJson(nlohmann::json::parse(R"({
        "timber_cottage": {
            "roof_style": "gable", "foundation": "crawlspace",
            "thickness": { "exterior_wall": 0.333, "interior_wall": 0.222,
                           "foundation_wall": 0.667, "floor": 0.333, "ceiling": 0.222 },
            "materials": { "structure": "Wood", "floor": "Wood", "roof": "Wood", "foundation": "Stone" },
            "roof": { "pitch": 0.8 }
        }
    })"));
    return *reg.get("timber_cottage");
}

// A uniform-height tower: `stories` floors of height 3 over a w×d footprint, an exterior door
// on story 0, and (optionally) a stair on each floor to the next at well [1,2,2,6].
BuildingProgram tower(int stories, int w, int d, const std::string& form,
                      const std::string& substructure, bool withStairs) {
    nlohmann::json j;
    j["name"] = "case"; j["style"] = "timber_cottage";
    j["footprint"] = nlohmann::json::array({w, d});
    j["substructure"] = substructure; j["roof_style"] = "gable";
    j["stories"] = nlohmann::json::array();
    for (int s = 0; s < stories; ++s) {
        nlohmann::json room;
        room["id"] = "r" + std::to_string(s);
        room["rect"] = nlohmann::json::array({0, 0, w, d});
        room["purpose"] = "living";
        nlohmann::json story;
        story["height"] = 3;
        story["rooms"] = nlohmann::json::array({room});
        story["portals"] = nlohmann::json::array();
        story["stairs"] = nlohmann::json::array();
        if (s == 0)
            story["portals"].push_back({{"between", {"exterior", "r0"}},
                                        {"pos", {0, d / 2}}, {"width", 1}, {"height", 2}, {"kind", "door"}});
        if (withStairs && s < stories - 1) {
            nlohmann::json st;
            st["from_story"] = s; st["to_story"] = s + 1;
            st["rect"] = nlohmann::json::array({1, 2, 2, 6}); st["form"] = form;
            story["stairs"].push_back(st);
        }
        j["stories"].push_back(story);
    }
    return BuildingProgram::fromJson(j);
}

// A single-story two-room layout (hall + kitchen) tiling a 7x9 footprint, with the exterior door
// on the hall. `connected` adds the hall<->kitchen interior arch; when false the kitchen is SEALED.
BuildingProgram twoRoom(bool connected) {
    nlohmann::json j;
    j["name"] = "2room"; j["style"] = "timber_cottage";
    j["footprint"] = nlohmann::json::array({7, 9});
    j["substructure"] = "crawlspace"; j["roof_style"] = "gable";
    nlohmann::json hall, kitchen, story;
    hall["id"] = "hall"; hall["rect"] = nlohmann::json::array({0, 0, 4, 9}); hall["purpose"] = "living";
    kitchen["id"] = "kitchen"; kitchen["rect"] = nlohmann::json::array({4, 0, 3, 9}); kitchen["purpose"] = "kitchen";
    story["height"] = 3; story["rooms"] = nlohmann::json::array({hall, kitchen});
    story["portals"] = nlohmann::json::array();
    story["portals"].push_back({{"between", {"exterior", "hall"}}, {"pos", {0, 4}}, {"width", 1}, {"height", 2}, {"kind", "door"}});
    if (connected)
        story["portals"].push_back({{"between", {"hall", "kitchen"}}, {"pos", {4, 4}}, {"width", 1}, {"height", 2}, {"kind", "arch"}});
    story["stairs"] = nlohmann::json::array();
    j["stories"] = nlohmann::json::array({story});
    return BuildingProgram::fromJson(j);
}

// A 1-story building whose rooms are AUTO-GENERATED by generate_room_layout (placer #05) — no
// hand-authoring. Must pass the harness floors (L2) + rooms (L3) layers like any other building.
BuildingProgram generated(int W, int D, int targetRooms, unsigned seed, bool connectInterior = true) {
    RoomLayout rl = generateRoomLayout(W, D, targetRooms, seed);
    nlohmann::json j;
    j["name"] = "gen"; j["style"] = "timber_cottage";
    j["footprint"] = nlohmann::json::array({W, D});
    j["substructure"] = "crawlspace"; j["roof_style"] = "gable";
    nlohmann::json story;
    story["height"] = 3; story["rooms"] = nlohmann::json::array();
    story["portals"] = nlohmann::json::array(); story["stairs"] = nlohmann::json::array();
    j["stories"] = nlohmann::json::array({story});
    BuildingProgram p = BuildingProgram::fromJson(j);
    p.stories[0].rooms = rl.rooms;       // inject the generated partition + doors
    p.stories[0].portals = rl.portals;
    if (!connectInterior) {              // NEGATIVE CONTROL: keep only the exterior entrance ->
        std::vector<ProgPortal> ext;     // interior rooms become unreachable from the entrance room
        for (const auto& pt : p.stories[0].portals)
            if (pt.a == "exterior" || pt.b == "exterior") ext.push_back(pt);
        p.stories[0].portals = ext;
    }
    return p;
}

// A building whose interior is filled by the CORE SEAM `autofillRoomLayout` — the SAME function the

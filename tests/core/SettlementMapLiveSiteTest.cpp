double secondsSince(const std::chrono::steady_clock::time_point& t0) {
    return std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
}

// M5b-1 (chain 97): the route's APPROACH as a vertical section along the straight line from `from` to `to`, one
// column per micro step (the longer axis steps by 1, the other interpolated), rows = micro y top to bottom: '#'
// solid, '.' air, 'F' the probe fits AND is supported with its feet there (a standable cell), 'S' the start's
// column, 'G' the goal's. A step the walker cannot take reads as a riser taller than 4 between two F's.
void printApproachSection(ChunkManager& cm, const glm::ivec3& from, const glm::ivec3& to) {
    const std::function<bool(int, int, int)> occ = [&cm](int x, int y, int z) { return cm.occupiedMicro(glm::ivec3(x, y, z)); };
    Core::AgentBox box;
    Core::TraversalProbe probe(occ, box);
    const int dx = to.x - from.x, dz = to.z - from.z;
    const int n = std::max(std::abs(dx), std::abs(dz));
    if (n <= 0) return;
    const int yLo = std::min(from.y, to.y) - 12, yHi = std::max(from.y, to.y) + 20;
    std::vector<glm::ivec2> cols;
    for (int k = 0; k <= n; ++k)
        cols.push_back({from.x + (dx * k + (dx >= 0 ? n / 2 : -n / 2)) / n, from.z + (dz * k + (dz >= 0 ? n / 2 : -n / 2)) / n});
    std::printf("[ M5a-1 ]   approach section from (%d,%d,%d) to (%d,%d,%d): %d columns, micro y %d..%d (rows top to bottom; # solid, . air, F standable, S start, G goal)\n",
                from.x, from.y, from.z, to.x, to.y, to.z, n + 1, yLo, yHi);
    for (int y = yHi; y >= yLo; --y) {
        std::string row;
        for (int k = 0; k <= n; ++k) {
            const int x = cols[k].x, z = cols[k].y;
            char ch = occ(x, y, z) ? '#' : '.';
            if (ch == '.' && occ(x, y - 1, z) && probe.fits(x, y, z) && probe.supported(x, y, z)) ch = 'F';
            if (k == 0 && y == from.y) ch = 'S';
            if (k == n && y == to.y) ch = 'G';
            row += ch;
        }
        std::printf("[ M5a-1 ]   y %5d %s%s\n", y, row.c_str(), (y % 9 == 0) ? "  <- cube edge" : "");
    }
    // the feet level the probe would stand at in each column (the top solid + 1 where it fits), for the risers
    std::string feet = "[ M5a-1 ]   feet per column:";
    int prev = INT_MIN;
    for (int k = 0; k <= n; ++k) {
        const int x = cols[k].x, z = cols[k].y;
        int f = INT_MIN;
        for (int y = yHi; y >= yLo; --y) if (!occ(x, y, z) && occ(x, y - 1, z) && probe.fits(x, y, z) && probe.supported(x, y, z)) { f = y; break; }
        feet += " " + (f == INT_MIN ? std::string("-") : std::to_string(f));
        if (f != INT_MIN && prev != INT_MIN && std::abs(f - prev) > box.maxStepUpMicro) feet += "!";
        prev = f;
    }
    std::printf("%s   (! = a riser over %d micro from the previous column)\n", feet.c_str(), box.maxStepUpMicro);
}


// The live site, resident: the chunk manager's own generator carries the recipe (the realizer and the planner
// sample THAT generator), and the chunks over the site rect plus a margin are generated from it.
struct LiveSiteRig {
    ChunkManager cm;
    // the template manager spawns into THIS chunk manager (RemoveKeepsWallTest's rig); chain 77 built it on a null
    // one and both arms died with an access violation at the first furnished croft
    ObjectTemplateManager templates{&cm};
    PlacedObjectManager placed{&cm, &templates, nullptr};
    WorldGenerator* gen = nullptr;
    const WorldForgeSite* site = nullptr;
    int chunksGenerated = 0, surfaceLo = INT_MAX, surfaceHi = INT_MIN;
    std::string why;

    bool setUp(int siteId, int marginU) { return setUpSite([siteId](const WorldForgeSite& s) { return s.id == siteId; }, marginU); }
    bool setUpTier(const std::string& tier, int marginU) {   // the lowest id of that tier
        return setUpSite([tier](const WorldForgeSite& s) { return s.tier == tier; }, marginU);
    }
    bool setUpSite(const std::function<bool(const WorldForgeSite&)>& pick, int marginU) {
        const auto t0 = std::chrono::steady_clock::now();
        cm.initialize(VK_NULL_HANDLE, VK_NULL_HANDLE);
        cm.configureStreamingGeneration(true, WorldGenerator::GenerationType::Perlin, 20260816u);
        gen = cm.getStreamingGenerator();
        if (!gen) { why = "no streaming generator"; return false; }
        gen->applyRecipe(civRecipe(20260816u));
        const WorldForgePlan* box = gen->worldForge();
        if (!box) { why = "the recipe produced no WorldForge plan"; return false; }
        for (const auto& s : box->sites()) if (pick(s) && (!site || s.id < site->id)) site = &s;
        if (!site) { why = "no site matches the pick"; return false; }
        templates.loadTemplates("resources/templates");
        const double tPlan = secondsSince(t0);
        const int x0 = site->pos.x - site->width / 2 - marginU, x1 = site->pos.x + site->width / 2 + marginU;
        const int z0 = site->pos.y - site->depth / 2 - marginU, z1 = site->pos.y + site->depth / 2 + marginU;
        for (int x = x0; x <= x1; ++x)
            for (int z = z0; z <= z1; ++z) {
                const int sy = gen->sampleSurface(x, z).surfaceY;
                surfaceLo = std::min(surfaceLo, sy);
                surfaceHi = std::max(surfaceHi, sy);
            }
        // the chunk rows from 24 u below the lowest surface (grading, cellars) to 40 u above the highest (roofs)
        // chain 114: a hall house's chimney cap reached past surface + 40 (one voxel of 91354 "not materialized" refused
        // the lot twice); 64 (the rig's range, stated)
        const int y0 = std::max(0, surfaceLo - 24), y1 = surfaceHi + 64;
        for (int cx = floorDiv32(x0); cx <= floorDiv32(x1); ++cx)
            for (int cz = floorDiv32(z0); cz <= floorDiv32(z1); ++cz)
                for (int cy = floorDiv32(y0); cy <= floorDiv32(y1); ++cy) {
                    const glm::ivec3 cc(cx, cy, cz);
                    auto owned = Phyxel::ForgeTest::genChunkAt(*gen, cc);
                    cm.chunkMap[cc] = owned.get();
                    cm.chunks.push_back(std::move(owned));
                    ++chunksGenerated;
                }
        std::printf("[ M5a-1 ] rig: site %d (%s) centre (%d, %d) %d x %d seed %u surfaceY %.1f; margin %d u, surface %d..%d, "
                    "%d chunks generated (recipe + plan + templates %.1f s, chunks %.1f s)\n",
                    site->id, site->tier.c_str(), site->pos.x, site->pos.y, site->width, site->depth, site->seed,
                    site->surfaceY, marginU, surfaceLo, surfaceHi, chunksGenerated, tPlan, secondsSince(t0) - tPlan);
        return true;
    }

    bool solidMicro(int mx, int my, int mz) {
        const int wx = floorDivN(mx, 9), wy = floorDivN(my, 9), wz = floorDivN(mz, 9);
        auto it = cm.chunkMap.find(glm::ivec3(floorDiv32(wx), floorDiv32(wy), floorDiv32(wz)));
        if (it == cm.chunkMap.end() || !it->second) return false;
        Chunk& c = *it->second;
        const glm::ivec3 lp(floorModN(wx, 32), floorModN(wy, 32), floorModN(wz, 32));
        if (c.getCubeAt(lp)) return true;
        const glm::ivec3 sp(floorModN(mx, 9) / 3, floorModN(my, 9) / 3, floorModN(mz, 9) / 3);
        if (c.hasSubcubeAt(lp, sp)) return true;
        const glm::ivec3 mp(floorModN(mx, 3), floorModN(my, 3), floorModN(mz, 3));
        return c.getMicrocubeAt(lp, sp, mp) != nullptr;
    }

    // The micro occupancy around a pinch at the feet level and above: one 25 x 25 slice per level (rows = z, columns =
    // x; '#' solid, '.' free, 'S' pinch_from, 'G' pinch_to), so a lateral pinch (fixtures) reads as well as a step.
    void occupancySlice(const glm::ivec3& pf, const glm::ivec3& pt) {
        // chain 78: the chunk getters read empty air around a pinch the gate's sampler refuses - print both
        for (const int dy : {0, 4, 9, 13, 16}) {
            const int y = pf.y + dy;
            std::printf("[ M5a-1 ]   occupancy at micro y %d (feet %+d), x %d..%d left to right, z %d..%d top to bottom; "
                        "left grid = ChunkManager::occupiedMicro (the gate's sampler), right grid = the chunk getters:\n",
                        y, dy, pf.x - 12, pf.x + 12, pf.z - 12, pf.z + 12);
            for (int z = pf.z - 12; z <= pf.z + 12; ++z) {
                std::string a, b;
                for (int x = pf.x - 12; x <= pf.x + 12; ++x) {
                    char ca = cm.occupiedMicro(glm::ivec3(x, y, z)) ? '#' : '.', cb = solidMicro(x, y, z) ? '#' : '.';
                    if (x == pf.x && z == pf.z && y == pf.y) ca = cb = 'S';
                    else if (x == pt.x && z == pt.z && y == pt.y) ca = cb = 'G';
                    a += ca; b += cb;
                }
                std::printf("[ M5a-1 ]     z %6d %s   %s%s\n", z, a.c_str(), b.c_str(), (z % 9 == 0) ? "  <- cube edge" : "");
            }
        }
        // the probe's own verdicts at both pinch cells, as the gate's first-step diagnostics print them
        const std::function<bool(int, int, int)> occ = [this](int x, int y, int z) { return cm.occupiedMicro(glm::ivec3(x, y, z)); };
        Core::AgentBox box;
        Core::TraversalProbe probe(occ, box);
        for (const glm::ivec3& st : {pf, pt}) {
            static const int ddx[4] = {1, -1, 0, 0}, ddz[4] = {0, 0, 1, -1};
            std::string fs = "fits=" + std::to_string(probe.fits(st.x, st.y, st.z)) + " sup=" + std::to_string(probe.supported(st.x, st.y, st.z));
            for (int d = 0; d < 4; ++d) {
                fs += " | d(" + std::to_string(ddx[d]) + "," + std::to_string(ddz[d]) + ")";
                for (int h = -box.maxStepUpMicro; h <= box.maxStepUpMicro; ++h)
                    fs += " h" + std::to_string(h) + ":" + (probe.fits(st.x + ddx[d], st.y + h, st.z + ddz[d]) ? "F" : "-")
                          + (probe.supported(st.x + ddx[d], st.y + h, st.z + ddz[d]) ? "S" : "-");
            }
            std::printf("[ M5a-1 ]   probe at (%d,%d,%d): %s\n", st.x, st.y, st.z, fs.c_str());
        }
        // the box's envelope at pinch_to: every occupied cell inside it (half-width %d, height %d)
        int inside = 0;
        for (int y = pt.y; y < pt.y + box.heightMicro; ++y)
            for (int x = pt.x - box.halfWidthMicro; x <= pt.x + box.halfWidthMicro; ++x)
                for (int z = pt.z - box.halfWidthMicro; z <= pt.z + box.halfWidthMicro; ++z)
                    if (cm.occupiedMicro(glm::ivec3(x, y, z))) {
                        if (++inside <= 12) std::printf("[ M5a-1 ]   occupied inside the box at pinch_to: (%d,%d,%d)\n", x, y, z);
                    }
        std::printf("[ M5a-1 ]   %d occupied cells inside the box envelope at pinch_to (half-width %d, height %d micro)\n",
                    inside, box.halfWidthMicro, box.heightMicro);
    }

    // The GOAL of a blocked route (chain 79: both floods ~26k cells, the pinch pair open air on both samplers, every step
    // accepted - so the forward walk fails at its goal, not at the pinch): the `to` column's solids, the fixture whose
    // bbox holds the goal cube, whether the pinch pair connects on its own, and how close a wide flood from `from` gets
    // to `to` in x/z.
    void goalCheck(const glm::ivec3& from, const glm::ivec3& to, int goalRadius, const glm::ivec3& pf, const glm::ivec3& pt) {
        std::string col;
        for (int y = to.y - 9; y <= to.y + 17; ++y) col += cm.occupiedMicro(glm::ivec3(to.x, y, to.z)) ? '#' : '.';
        std::printf("[ M5a-1 ]   goal: from (%d,%d,%d) to (%d,%d,%d) radius %d; the `to` column y %d..%d bottom to top: %s\n",
                    from.x, from.y, from.z, to.x, to.y, to.z, goalRadius, to.y - 9, to.y + 17, col.c_str());
        const int gcx = floorDivN(to.x, 9), gcz = floorDivN(to.z, 9);
        for (const auto& [id, o] : placed.getAllObjects()) {
            if (o.category != "template") continue;
            if (gcx >= o.boundingMin.x && gcx <= o.boundingMax.x && gcz >= o.boundingMin.z && gcz <= o.boundingMax.z)
                std::printf("[ M5a-1 ]   goal cube (%d, %d) lies inside fixture %s (%s) bbox (%d,%d,%d)-(%d,%d,%d)\n", gcx, gcz, id.c_str(),
                            o.templateName.c_str(), o.boundingMin.x, o.boundingMin.y, o.boundingMin.z, o.boundingMax.x, o.boundingMax.y, o.boundingMax.z);
        }
        const std::function<bool(int, int, int)> occ = [this](int x, int y, int z) { return cm.occupiedMicro(glm::ivec3(x, y, z)); };
        Core::AgentBox box;
        Core::TraversalProbe probe(occ, box);
        const glm::ivec3 lo = glm::min(from, to) - glm::ivec3(54, 18, 54), hi = glm::max(from, to) + glm::ivec3(54, 30, 54);
        const bool pair = probe.reachable(pf, pt - glm::ivec3(1, 9, 1), pt + glm::ivec3(1, 9, 1), lo, hi);
        const auto flood = probe.flood(from, lo, hi);
        int within4 = 0, within13 = 0, within4y = 0;
        for (const auto& c : flood) {
            const int dx = std::abs(c.x - to.x), dz = std::abs(c.z - to.z);
            if (dx <= goalRadius && dz <= goalRadius) { ++within4; if (std::abs(c.y - to.y) <= 9) ++within4y; }
            if (dx <= goalRadius + 9 && dz <= goalRadius + 9) ++within13;
        }
        std::printf("[ M5a-1 ]   the pinch pair connects on its own: %s; a wide flood from `from` (%zu cells, band (%d,%d,%d)-(%d,%d,%d)): "
                    "%d cells within the goal's x/z window (%d of them within 9 micro of the goal's y), %d within one cube of it\n",
                    pair ? "YES" : "NO", flood.size(), lo.x, lo.y, lo.z, hi.x, hi.y, hi.z, within4, within4y, within13);
    }

    void approachProfile(const glm::ivec3& from, const glm::ivec3& to) { printApproachSection(cm, from, to); }

    // The fixtures the furnisher placed within 12 cubes of a pinch (the live pinch sat between a bench and a table).
    void fixturesNear(const glm::ivec3& pfMicro) {
        const int cx = floorDivN(pfMicro.x, 9), cz = floorDivN(pfMicro.z, 9);
        int n = 0;
        for (const auto& [id, o] : placed.getAllObjects()) {
            if (o.category != "template") continue;
            if (std::abs(o.position.x - cx) > 12 || std::abs(o.position.z - cz) > 12) continue;
            std::printf("[ M5a-1 ]   fixture %s (%s) at cube (%d,%d,%d) micro anchor (%d,%d,%d) rot %d bbox (%d,%d,%d)-(%d,%d,%d) parent %s\n",
                        id.c_str(), o.templateName.c_str(), o.position.x, o.position.y, o.position.z, o.microAnchor.x, o.microAnchor.y,
                        o.microAnchor.z, o.rotation, o.boundingMin.x, o.boundingMin.y, o.boundingMin.z, o.boundingMax.x, o.boundingMax.y,
                        o.boundingMax.z, o.parentId.c_str());
            ++n;
        }
        std::printf("[ M5a-1 ]   %d fixtures within 12 cubes of the pinch; %zu placed objects in all\n", n, placed.getAllObjects().size());
    }

    // The floor across a pinch: for each micro column along the route axis through pinch_from, the top solid
    // micro cell within 2 cubes below / 1 cube above the pinch level (the step the probe cannot climb is the jump
    // between neighbouring columns), with the cube-level material at the top cell's cube.
    void floorProfile(const glm::ivec3& pf, const glm::ivec3& pt) {
        const bool alongX = (pf.x != pt.x) || (pf.z == pt.z);
        std::printf("[ M5a-1 ]   floor profile along %s through pinch_from (%d,%d,%d) -> pinch_to (%d,%d,%d), micro cells "
                    "(d = offset from pinch_from; top = highest solid micro y in [%d, %d], - = none):\n",
                    alongX ? "x" : "z", pf.x, pf.y, pf.z, pt.x, pt.y, pt.z, pf.y - 18, pf.y + 9);
        for (int d = -12; d <= 12; ++d) {
            const int mx = alongX ? pf.x + d : pf.x, mz = alongX ? pf.z : pf.z + d;
            int top = INT_MIN;
            for (int my = pf.y + 9; my >= pf.y - 18; --my) if (solidMicro(mx, my, mz)) { top = my; break; }
            const char* mark = (d == 0) ? " <- pinch_from" : ((alongX ? mx == pt.x : mz == pt.z) ? " <- pinch_to" : "");
            if (top == INT_MIN) std::printf("[ M5a-1 ]     d %+3d (%d,%d): top -%s\n", d, mx, mz, mark);
            else {
                const int wx = floorDivN(mx, 9), wy = floorDivN(top, 9), wz = floorDivN(mz, 9);
                const Cube* cube = cm.getCubeAt(glm::ivec3(wx, wy, wz));
                std::printf("[ M5a-1 ]     d %+3d (%d,%d): top %d (cube y %d %s, micro %d of 9)%s\n", d, mx, mz, top, wy,
                            cube ? "full cube" : "sub/micro", floorModN(top, 9), mark);
            }
        }
    }
};

// Plan the site through the canonical params and run every unit; the gate's verdict + the record for the ledger.
nlohmann::json realize(LiveSiteRig& rig, bool legacyLayout, const nlohmann::json& overrides = nlohmann::json::object()) {
    nlohmann::json params = WorldForgeBuildService::settlementParamsFor(*rig.gen->worldForge(), *rig.site);
    for (auto it = overrides.begin(); it != overrides.end(); ++it) params[it.key()] = it.value();
    if (legacyLayout) params["legacy_layout"] = true;
    std::printf("[ M5a-1 ] params (%s): %s\n", legacyLayout ? "the layout as built, the CONTROL" : "the MAP", params.dump().c_str());
    SettlementBuildService::Deps deps;
    deps.chunkManager = &rig.cm;
    deps.templates = &rig.templates;
    deps.placedObjects = &rig.placed;
    const auto t0 = std::chrono::steady_clock::now();
    auto plan = SettlementBuildService::plan(params, deps);
    nlohmann::json out;
    if (!plan.ok()) {
        std::printf("[ M5a-1 ] plan REFUSED in %.1f s: %s\n", secondsSince(t0), plan.error.dump().c_str());
        out["plan_error"] = plan.error;
        out["map"] = plan.map;
        return out;
    }
    std::printf("[ M5a-1 ] planned in %.1f s: %zu buildings queued, %zu units, morphology %s\n", secondsSince(t0),
                plan.queuedBuilds.size(), plan.units.size(), plan.program.value("morphology", std::string("?")).c_str());
    if (plan.map.is_object()) {
        std::printf("[ M5a-1 ]   map: %zu lots, %zu ways, %zu nodes, entry %d, bake %.2f ms, target %d, dropped %zu\n",
                    plan.map.value("lots", nlohmann::json::array()).size(), plan.map.value("ways", nlohmann::json::array()).size(),
                    plan.map.value("nodes", nlohmann::json::array()).size(), plan.map.value("entry_node", -1),
                    plan.map.value("bake_ms", 0.0), plan.map.value("target_lots", -1),
                    plan.map.value("dropped_lots", nlohmann::json::array()).size());
        for (const auto& l : plan.map.value("lots", nlohmann::json::array()))
            std::printf("[ M5a-1 ]   lot %d: %s rect %s footprint %s orientation %d setback %d stories %d ground %s way %d\n",
                        l.value("id", -1), l.value("typology", std::string("?")).c_str(), l.value("rect", nlohmann::json()).dump().c_str(),
                        l.value("footprint", nlohmann::json()).dump().c_str(), l.value("orientation", -1), l.value("setback", -1),
                        l.value("stories", -1), l.value("ground", std::string("?")).c_str(), l.value("way", -1));
    }
    for (auto& u : plan.units) {
        const auto tu = std::chrono::steady_clock::now();
        u.run();
        std::printf("[ M5a-1 ]   unit %-28s %6.1f s\n", u.label.c_str(), secondsSince(tu));
    }
    const nlohmann::json walk = plan.walkability ? *plan.walkability : nlohmann::json::object();
    out = SettlementBuildService::gateOutcome(walk, false);
    out["queued"] = plan.queuedBuilds.size();
    out["paths"] = plan.paths ? *plan.paths : nlohmann::json::object();   // M5b-1: the ways unit's record (paved columns, legs)
    std::printf("[ M5a-1 ] paths unit: %s\n", out["paths"].dump().c_str());
    out["lot_failures"] = plan.lotFailures ? *plan.lotFailures : nlohmann::json::array();
    out["seats"] = plan.seats ? *plan.seats : nlohmann::json::array();
    out["built_doors"] = plan.builtDoors ? *plan.builtDoors : nlohmann::json::array();
    out["map"] = plan.map;
    out["skipped"] = walk.value("skipped", 0);
    out["doors"] = walk.value("doors", -1);    // -1: the gate result carries no door count (chain 74)
    out["built"] = walk.value("built", -1);
    size_t fixtures = 0;
    for (const auto& [id, o] : rig.placed.getAllObjects()) if (o.category == "template") ++fixtures;
    out["fixtures"] = fixtures;
    // every "door -> room" route's recorded goal box against roomGoalBox on the building's OWN rooms (the placed
    // structure whose bbox holds the route's start; its "building" metadata carries the rooms, building-local)
    int goalChecked = 0, goalWrong = 0;
    for (const auto& r : walk.value("routes", nlohmann::json::array())) {
        const std::string label = r.value("label", std::string());
        const auto k = label.find(": door -> ");
        if (k == std::string::npos || !r.contains("goal_box") || !r.contains("from")) continue;
        const std::string purpose = label.substr(k + 10);
        const auto fr = r["from"];
        const glm::ivec3 from(fr[0].get<int>(), fr[1].get<int>(), fr[2].get<int>());
        const int cx = floorDivN(from.x, 9), cz = floorDivN(from.z, 9);
        const PlacedObject* bld = nullptr;
        for (const auto& [id, o] : rig.placed.getAllObjects())
            if (o.category == "structure" && cx >= o.boundingMin.x && cx <= o.boundingMax.x && cz >= o.boundingMin.z && cz <= o.boundingMax.z) bld = &o;
        ++goalChecked;
        if (!bld) { std::printf("[ M5a-1 ]   goal box of '%s': no placed structure holds its start (%d,%d)\n", label.c_str(), cx, cz); ++goalWrong; continue; }
        const auto& g = r["goal_box"];
        const glm::ivec3 lo(g[0].get<int>(), g[1].get<int>(), g[2].get<int>()), hi(g[3].get<int>(), g[4].get<int>(), g[5].get<int>());
        bool matched = false;
        std::string tried;
        for (const auto& rm : bld->metadata.value("building", nlohmann::json::object()).value("rooms", nlohmann::json::array())) {
            if (rm.value("story", 0) != 0 || rm.value("purpose", std::string()) != purpose) continue;
            const auto& rc = rm["rect"];
            const auto gb = SettlementBuildService::roomGoalBox(bld->position.x + rc[0].get<int>(), bld->position.z + rc[1].get<int>(),
                                                                rc[2].get<int>(), rc[3].get<int>(), from.y);
            tried += " (" + std::to_string(gb.first.x) + "," + std::to_string(gb.first.y) + "," + std::to_string(gb.first.z) + ")-("
                     + std::to_string(gb.second.x) + "," + std::to_string(gb.second.y) + "," + std::to_string(gb.second.z) + ")";
            if (gb.first == lo && gb.second == hi) { matched = true; break; }
        }
        if (!matched) {
            std::printf("[ M5a-1 ]   goal box of '%s' (%d,%d,%d)-(%d,%d,%d) matches no room of %s at (%d,%d,%d); the formula gave%s\n",
                        label.c_str(), lo.x, lo.y, lo.z, hi.x, hi.y, hi.z, bld->id.c_str(), bld->position.x, bld->position.y, bld->position.z,
                        tried.empty() ? " nothing (no room of that purpose)" : tried.c_str());
            ++goalWrong;
        }
    }
    out["goal_boxes_checked"] = goalChecked;
    out["goal_boxes_wrong"] = goalWrong;
    std::printf("[ M5a-1 ] goal boxes: %d door -> room routes checked against roomGoalBox on the buildings' rooms, %d wrong\n", goalChecked, goalWrong);
    std::printf("[ M5a-1 ] gate: %s - %d walkable, %d blocked, %d skipped over %d doors of %d built; %zu lot failures; %zu fixtures placed; %.1f s in all\n",
                out.value("gate", std::string("?")).c_str(), out.value("walkable", 0), out.value("blocked", 0), out.value("skipped", 0),
                out.value("doors", -1), out.value("built", -1), out["lot_failures"].size(), fixtures, secondsSince(t0));
    for (const auto& r : walk.value("routes", nlohmann::json::array())) {
        if (r.value("walkable", true)) continue;
        const auto pf = r.value("pinch_from", nlohmann::json::array({0, 0, 0})), pt = r.value("pinch_to", nlohmann::json::array({0, 0, 0}));
        std::printf("[ M5a-1 ]   BLOCKED %s: pinch (%d,%d,%d) -> (%d,%d,%d) gap %d micro, reached %d / %d%s%s%s\n",
                    r.value("label", std::string("?")).c_str(), pf[0].get<int>(), pf[1].get<int>(), pf[2].get<int>(),
                    pt[0].get<int>(), pt[1].get<int>(), pt[2].get<int>(), r.value("pinch_gap_micro", 0),
                    r.value("reached_from_start", 0), r.value("reached_from_goal", 0),
                    r.value("start_unsupported", false) ? " START-UNSUPPORTED" : "", r.value("goal_unsupported", false) ? " GOAL-UNSUPPORTED" : "",
                    r.value("one_way", false) ? " ONE-WAY" : "");
        if (r.contains("first_steps")) std::printf("[ M5a-1 ]     %s\n", r.value("first_steps", std::string()).c_str());
        const glm::ivec3 pfv(pf[0].get<int>(), pf[1].get<int>(), pf[2].get<int>()), ptv(pt[0].get<int>(), pt[1].get<int>(), pt[2].get<int>());
        rig.floorProfile(pfv, ptv);
        rig.occupancySlice(pfv, ptv);
        rig.fixturesNear(pfv);
        if (r.contains("from") && r.contains("to")) {
            const auto fr = r["from"], to = r["to"];
            rig.goalCheck(glm::ivec3(fr[0].get<int>(), fr[1].get<int>(), fr[2].get<int>()),
                          glm::ivec3(to[0].get<int>(), to[1].get<int>(), to[2].get<int>()), r.value("goal_radius", 4), pfv, ptv);
            rig.approachProfile(glm::ivec3(fr[0].get<int>(), fr[1].get<int>(), fr[2].get<int>()),
                                glm::ivec3(to[0].get<int>(), to[1].get<int>(), to[2].get<int>()));
        }
    }
    for (const auto& f : out["lot_failures"]) std::printf("[ M5a-1 ]   lot failure: %s\n", f.dump().c_str());
    return out;
}

